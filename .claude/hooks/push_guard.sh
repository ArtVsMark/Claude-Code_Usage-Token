#!/bin/sh
# Обёртка стража толчка: зовёт push_guard.py ИНТЕРПРЕТАТОРОМ ПЛАНКИ (#154).
#
# ПОЧЕМУ НЕ `python3` НАПРЯМУЮ. Хук исполняется в окружении процесса окна, а не
# в PATH, который хук старта выставил командам (CLAUDE_ENV_FILE действует только
# на них). Голый `python3` там системный — в облачном окне 3.11, — и страж в
# грамматике 3.14 упал бы на нём SyntaxError'ом. Ненулевой код, кроме 2,
# площадка считает НЕблокирующей ошибкой: толчок прошёл бы без проверки, молча.
#
# ГДЕ ИЩЕТСЯ ИНТЕРПРЕТАТОР — ТРИ МЕСТА, И ТРЕТЬЕ НАШЕ, А НЕ КАТАЛОГА. Образец
# каталога знает только `python<планка>` в PATH. У нас локальное окно — Windows,
# где такой команды нет вовсе, а есть лаунчер `py -<планка>`; с одной первой
# ступенью обёртка закрыла бы локальному окну каждый толчок. Порядок:
#   1. `python<планка>` в PATH — облачное окно (его ставит хук старта);
#   2. окружение проекта .venv, если оно на планке — любое окно;
#   3. лаунчер `py -<планка>` — Windows.
#
# НЕТ ИНТЕРПРЕТАТОРА ПЛАНКИ — ТОЛЧОК ЗАКРЫТ, ОСТАЛЬНОЕ ОТКРЫТО. Хук стоит на
# каждой команде оболочки; закрыть всё значило бы обездвижить окно из-за сбоя
# при старте. Закрывается только то, что страж и сторожит.
dir=$(dirname "$0")
root="${CLAUDE_PROJECT_DIR:-.}"
. "$dir/floor.sh"
floor=$(planka_floor "$root/pyproject.toml")

na_planke() {
  [ "$("$@" -c 'import sys; print("%d.%d" % sys.version_info[:2])' </dev/null 2>/dev/null)" = "$floor" ]
}

if [ -n "$floor" ]; then
  py=$(command -v "python$floor" 2>/dev/null)
  if [ -n "$py" ]; then
    exec "$py" "$dir/push_guard.py"
  fi
  for venv in "$root/.venv/bin/python" "$root/.venv/Scripts/python.exe"; do
    if [ -x "$venv" ] && na_planke "$venv"; then
      exec "$venv" "$dir/push_guard.py"
    fi
  done
  if command -v py >/dev/null 2>&1 && na_planke py "-$floor"; then
    exec py "-$floor" "$dir/push_guard.py"
  fi
fi

# ЗАПАСНОЙ РАЗБОР ГРУБЕЕ СТРАЖА, И ГРАНИЦА ЕГО СДВИНУТА В СТОРОНУ ЗАКРЫТИЯ.
# Приём каталога: из входа берётся ТОЛЬКО поле `command` (не весь JSON, где
# `cwd` и пути могут нести слово `git`), с него снимаются кавычки и обратные
# косые, и закрывается команда, где `push` стоит после `git`. Лишне закрытое
# (`git stash push`, `git log | grep push`) стоит одной команды в окне, которое
# и так сломано. ГРАНИЦА: косвенный толчок — `c=push; git $c`, подстановка,
# алиас — не видит ни этот разбор, ни сам страж. Поле достаётся awk, потому что
# python здесь как раз и нет; ключ ищется как ключ — `"command"` с двоеточием.
input=$(cat | awk '
  { buf = buf $0 "\n" }
  END {
    if (!match(buf, /"command"[ \t\n]*:[ \t\n]*"/)) {
      gsub(/["\047\\]/, "", buf)
      print buf
      exit
    }
    rest = substr(buf, RSTART + RLENGTH)
    out = ""
    for (k = 1; k <= length(rest); k++) {
      c = substr(rest, k, 1)
      if (c == "\\") { k++; continue }
      if (c == "\"") break
      out = out c
    }
    gsub(/\047/, "", out)
    print out
  }')
case "$input" in
  *git*push*)
    echo "страж толчка не запущен: интерпретатора планки python${floor:-?} нет в окне (искался в PATH, в .venv проекта и лаунчером py). Толчок закрыт до починки: без стража он ушёл бы непроверенным. Перезапустите окно или поставьте python${floor:-?}." >&2
    exit 2 ;;
esac
exit 0
