"""Толчок в чужую ветку отвергается ДО вызова git (правило 012 каталога).

Конвейер такого не ловит по построению: он видит артефакт, а к его запуску
ветка уже сдвинута. Поэтому заслон стоит **перед вызовом инструмента** — хук
`PreToolUse`, объявленный в `.claude/settings.json`.

## Что отвергается

Толчок, у которого **источник или цель** — не текущая голова:

* `git push origin чужая-ветка` — берёт ЛОКАЛЬНУЮ ветку `чужая-ветка` и
  отправляет её: публикует не то, над чем идёт работа, и молча;
* `git push origin HEAD:чужая` — то, на чём стоишь, уезжает в ЧУЖУЮ ветку;
* `git push --all` и `--mirror` — уезжают все ветки разом, и чужие тоже;
* **любой толчок с головы `main`** и любой толчок В `main` — общую ветку окно не
  толкает никогда, под каким бы именем она ни стояла.

Цель — **правая часть refspec**. Прежде судился только источник, и `HEAD:<что
угодно>` считался законным: `git push --force origin HEAD:main` проходил с
кодом 0, и `main` спасал только ruleset площадки (#151, находка аудита #139).
Решение владельца 2 октября (#155): цель судится так же, как источник; приём —
`branch_of`/`refused` заслона проекта механизмов.

## Что разрешено

* **`git push`** и **`git push origin`** — уезжает текущая ветка;
* **`git push origin <текущая>`**, **`HEAD:<текущая>`**, **`<текущая>:<текущая>`**
  — то же самое, названное вслух.

Разрешено и всё, что не является толчком: заслон судит только `git push`.

## Граница

Хук работает **только в агентских окнах** — он объявлен в настройках Claude
Code и вызывается им. Человек, толкающий из терминала, им не защищён, и это
названо здесь, а не обнаружится потом. Предмет правила при этом именно
агентский: ветку `agent/**` ведёт окно, и перезапуск окна не делает её ничьей.
"""

from __future__ import annotations

import json
import re
import shlex
import subprocess
import sys

#: Отказать в вызове. Так Claude Code понимает «не запускай, вот почему».
DENY = 2

#: Локальный git отвечает мгновенно; дедлайн назван, потому что без него вызов
#: при истёкшем ключе ждёт ввода с терминала, которого в окне нет.
LOCAL_TIMEOUT = 10

_ФЛАГ = re.compile(r"^-")


def текущая_ветка() -> str | None:
    """Имя головы. `None` — не репозиторий, отсоединённая голова или отказ git."""
    try:
        итог = subprocess.run(
            ("git", "rev-parse", "--abbrev-ref", "HEAD"),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=LOCAL_TIMEOUT,
            env={"GIT_TERMINAL_PROMPT": "0", "PATH": "/usr/bin:/bin:/usr/local/bin"},
        )
    except (OSError, subprocess.SubprocessError):
        return None
    имя = итог.stdout.strip()
    return имя if итог.returncode == 0 and имя and имя != "HEAD" else None


#: Соединители оболочки. Разбор идёт по СЫРОЙ строке, а не по токенам shlex:
#: `2>&1|tail` он отдаёт одним словом, и команда за трубой оставалась бы
#: приклеенной к предыдущей.
_СОЕДИНИТЕЛЬ = re.compile(r"&&|\|\||;|\||&|\n")

#: Признак heredoc. Его наличие ОТКЛЮЧАЕТ разбор целиком — см. `чужая_ветка`.
_HEREDOC = re.compile(r"<<")


#: Общая ветка. В неё окно не толкает ни под каким именем.
ОБЩАЯ = "main"

#: Флаги, уносящие все ветки разом: судить источник у них нечего — он «всё».
_ВСЕ_ВЕТКИ = frozenset({"--all", "--mirror", "--branches"})

#: Имя, которым отказ называет толчок всех веток.
ВСЕ_ВЕТКИ = "все ветки"


def чужая_ветка(команда: str, голова: str | None) -> str | None:
    """Чужая ветка, затронутая толчком, — или `None`, если толчок законный.

    Разбирается **каждая** команда строки: `cd … && git push чужая` прячет
    толчок за соединителем, и судить по первому слову значило бы не судить
    вовсе.

    ## Heredoc отключает разбор, и это названная граница

    Тело heredoc — **проза**, а не аргументы: описание коммита, тело задачи,
    текст документа. Разбору она неотличима от команды, и разбор ошибался
    ровно так: строка `git commit -F - <<'MSG' … MSG`, где в сообщении стояло
    «`git push origin ветка`», была объявлена толчком в ветку «docs» — первое
    слово заголовка коммита.

    Ложный отказ здесь дороже пропуска: его чинят отключением хука, а не
    исправлением команды (051). Поэтому команда с heredoc не судится вовсе, и
    это сказано вслух, а не обнаружится потом.
    """
    if голова is None or _HEREDOC.search(команда):
        return None

    for кусок in _СОЕДИНИТЕЛЬ.split(команда):
        try:
            слова = shlex.split(кусок)
        except ValueError:
            continue
        чужая = _затронутая(слова, голова)
        if чужая is not None:
            return чужая
    return None


def _ветка(ref: str) -> str:
    """Имя ветки из ссылки: `+refs/heads/x` → `x`."""
    return ref.removeprefix("+").removeprefix("refs/heads/")


def _затронутая(слова: list[str], голова: str) -> str | None:
    """Чужая ветка в одном вызове `git push` — или `None`.

    Источник и цель судятся порознь: источник — что уезжает, цель — куда.
    Законно, только когда обе стороны — текущая голова и голова не общая.
    """
    if len(слова) < 2 or слова[0] != "git" or "push" not in слова:
        return None
    после = слова[слова.index("push") + 1 :]
    if _ВСЕ_ВЕТКИ & set(после):
        return ВСЕ_ВЕТКИ
    позиционные = [с for с in после if not _ФЛАГ.match(с)]
    if голова == ОБЩАЯ:
        # С головы общей ветки окно не толкает ничего: `git push` без
        # refspec унёс бы именно её.
        return ОБЩАЯ
    if len(позиционные) < 2:
        # `git push` или `git push origin` — уедет текущая ветка.
        return None
    for refspec in позиционные[1:]:
        источник, _, цель = refspec.partition(":")
        if not _:
            цель = источник
        источник, цель = _ветка(источник), _ветка(цель)
        if источник not in {"", "HEAD", голова}:
            return источник
        if цель in {"", "HEAD"}:
            continue
        if цель != голова or цель == ОБЩАЯ:
            return цель
    return None


def main() -> int:
    try:
        событие = json.load(sys.stdin)
    except (ValueError, OSError):
        return 0

    вход = событие.get("tool_input")
    команда = вход.get("command", "") if isinstance(вход, dict) else ""
    if not isinstance(команда, str) or not команда.strip():
        return 0

    чужая = чужая_ветка(команда, текущая_ветка())
    if чужая is None:
        return 0

    print(
        f"толчок в ветку «{чужая}» при голове «{текущая_ветка()}» отвергнут "
        "(правило 012). Толкается то, над чем идёт работа, и туда же: `git push`, "
        "`git push origin <текущая>` или `git push origin HEAD:<текущая>`. "
        "Источник и цель обязаны быть текущей веткой, а в main окно не толкает "
        "никогда.",
        file=sys.stderr,
    )
    return DENY


if __name__ == "__main__":
    raise SystemExit(main())
