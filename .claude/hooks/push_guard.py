"""Толчок в чужую ветку отвергается ДО вызова git (правило 012 каталога).

Конвейер такого не ловит по построению: он видит артефакт, а к его запуску
ветка уже сдвинута. Поэтому заслон стоит **перед вызовом инструмента** — хук
`PreToolUse`, объявленный в `.claude/settings.json`.

## Что отвергается

Толчок, у которого источник назван **именем ветки, отличным от текущей головы**:
`git push origin чужая-ветка`. Такая команда берёт локальную ветку `чужая-ветка`
и отправляет её — то есть публикует не то, над чем идёт работа, и делает это
молча: git отвечает `Everything up-to-date` или отправляет чужие коммиты.

## Что разрешено, и почему именно это

* **`git push` без источника** — отправляется текущая ветка, ошибиться нечем;
* **`git push origin <текущая>`** — то же самое, названное вслух;
* **`git push origin HEAD:<ветка>`** — намерение выражено явно: «то, на чём я
  стою, туда». Это законный приём: так изменение уезжает в ветку с другим
  именем, не переключаясь на неё.

Разрешено и всё, что не является толчком: заслон судит только `git push`.

## Граница

Хук работает **только в агентских окнах** — он объявлен в настройках Claude
Code и вызывается им. Человек, толкающий из терминала, им не защищён, и это
названо здесь, а не обнаружится потом. Предмет правила при этом именно
агентский: ветку `agent/**` ведёт окно, и перезапуск окна не делает её ничьей.
"""

from __future__ import annotations

import json
import re
import shlex
import subprocess
import sys

#: Отказать в вызове. Так Claude Code понимает «не запускай, вот почему».
DENY = 2

#: Локальный git отвечает мгновенно; дедлайн назван, потому что без него вызов
#: при истёкшем ключе ждёт ввода с терминала, которого в окне нет.
LOCAL_TIMEOUT = 10

_ФЛАГ = re.compile(r"^-")


def текущая_ветка() -> str | None:
    """Имя головы. `None` — не репозиторий, отсоединённая голова или отказ git."""
    try:
        итог = subprocess.run(
            ("git", "rev-parse", "--abbrev-ref", "HEAD"),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=LOCAL_TIMEOUT,
            env={"GIT_TERMINAL_PROMPT": "0", "PATH": "/usr/bin:/bin:/usr/local/bin"},
        )
    except (OSError, subprocess.SubprocessError):
        return None
    имя = итог.stdout.strip()
    return имя if итог.returncode == 0 and имя and имя != "HEAD" else None


#: Соединители оболочки. Разбор идёт по СЫРОЙ строке, а не по токенам shlex:
#: `2>&1|tail` он отдаёт одним словом, и команда за трубой оставалась бы
#: приклеенной к предыдущей.
_СОЕДИНИТЕЛЬ = re.compile(r"&&|\|\||;|\||&|\n")

#: Признак heredoc. Его наличие ОТКЛЮЧАЕТ разбор целиком — см. `чужая_ветка`.
_HEREDOC = re.compile(r"<<")


def чужая_ветка(команда: str, голова: str | None) -> str | None:
    """Имя ветки, в которую толкают вместо текущей. `None` — толчок законный.

    Разбирается **каждая** команда строки: `cd … && git push чужая` прячет
    толчок за соединителем, и судить по первому слову значило бы не судить
    вовсе.

    ## Heredoc отключает разбор, и это названная граница

    Тело heredoc — **проза**, а не аргументы: описание коммита, тело задачи,
    текст документа. Разбору она неотличима от команды, и разбор ошибался
    ровно так: строка `git commit -F - <<'MSG' … MSG`, где в сообщении стояло
    «`git push origin ветка`», была объявлена толчком в ветку «docs» — первое
    слово заголовка коммита.

    Ложный отказ здесь дороже пропуска: его чинят отключением хука, а не
    исправлением команды (051). Поэтому команда с heredoc не судится вовсе, и
    это сказано вслух, а не обнаружится потом.
    """
    if голова is None or _HEREDOC.search(команда):
        return None

    for кусок in _СОЕДИНИТЕЛЬ.split(команда):
        try:
            слова = shlex.split(кусок)
        except ValueError:
            continue
        имя = _источник(слова)
        if имя is not None and имя != голова:
            return имя
    return None


def _источник(слова: list[str]) -> str | None:
    """Ветка-источник у `git push`. `None` — не толчок либо источник не назван."""
    if len(слова) < 2 or слова[0] != "git" or "push" not in слова:
        return None
    после = слова[слова.index("push") + 1 :]
    позиционные = [с for с in после if not _ФЛАГ.match(с)]
    if len(позиционные) < 2:
        # `git push` или `git push origin` — уедет текущая ветка.
        return None
    refspec = позиционные[1]
    if ":" in refspec:
        # `HEAD:ветка` и `ветка:ветка` — намерение выражено явно.
        источник = refspec.split(":", 1)[0]
        return None if источник in {"", "HEAD"} else источник
    return refspec.removeprefix("+")


def main() -> int:
    try:
        событие = json.load(sys.stdin)
    except (ValueError, OSError):
        return 0

    вход = событие.get("tool_input")
    команда = вход.get("command", "") if isinstance(вход, dict) else ""
    if not isinstance(команда, str) or not команда.strip():
        return 0

    чужая = чужая_ветка(команда, текущая_ветка())
    if чужая is None:
        return 0

    print(
        f"толчок в ветку «{чужая}» при голове «{текущая_ветка()}» отвергнут "
        "(правило 012). Толкается то, над чем идёт работа: `git push` без "
        "источника, `git push origin <текущая>` либо явное "
        "`git push origin HEAD:<ветка>`. Иначе уедет чужая локальная ветка, "
        "и git промолчит.",
        file=sys.stderr,
    )
    return DENY


if __name__ == "__main__":
    raise SystemExit(main())
