"""Белый список полей замера: незнакомое не попадает и не теряется (#7).

Замер уходит в git **навсегда**: хранилище append-only, а история не
переписывается. Поэтому здесь два разных требования, и путать их нельзя.

## Список белый, а не чёрный

Чёрный список не переживёт добавления нового поля в реестр сессий — а именно
так секрет и утекает: не через известное поле, а через незнакомое. В соседнем
проекте инцидент уже был: `save_json()` писал ответы API в файл без редакции
секретов, то есть инструмент диагностики сам создавал файл с несокрытыми
ключами.

Белый список переворачивает умолчание: незнакомое поле **не попадает** в замер,
пока его туда не внесли осознанно.

## Незнакомое поле расхода — отказ, а не тихая фильтрация

Молчаливая фильтрация закрывает утечку, но открывает другую дыру, и она
дороже. Новое поле внутри `usage` — это, скорее всего, **новое слагаемое
расхода**. Отфильтровав его молча, инструмент запишет заниженную сумму, и
шкала, откалиброванная по ней, будет неверной ровно на долю недоучтённого.
Проверить это по самим данным будет нечем: единственный источник — тот же
усечённый файл. Ровно тот дефект, что разобран в #18, только нанесённый себе.

Отсюда граница:

* незнакомое поле **вне** `usage` — метаданные сессии, нас не касаются:
  отбрасывается молча, потому что попасть в замер оно и не должно;
* незнакомое поле **внутри** `usage` — отказ. Громкий, с именем поля: замер
  не пишется, пока человек не решит, слагаемое это или нет.

Цена отказа названа честно: добавление поля в реестр остановит замеры до
правки списка. Это дешевле, чем граница в накопленных данных, до которой
расход учтён не полностью, — её уже не починить.
"""

from __future__ import annotations

from typing import Any

#: Пять чисел расхода. Ровно пять — решение по #18: светофор реагирует на
#: полный расход аккаунта, и сумма из трёх слагаемых занижена на непостоянную
#: долю. `cost_usd` недостающие не заменяет: это производная по чужой формуле,
#: и разложить её обратно на токены нечем.
USAGE_FIELDS: dict[str, str] = {
    "cache_read_tokens": "cache_read",
    "cache_write_tokens": "cache_write",
    "input_tokens": "input",
    "output_tokens": "output",
    "cost_usd": "cost_usd",
}

#: Состояние светофора. `isUsingOverage` в замер не берётся: на шкалу он не
#: влияет, а поле, добавленное «на всякий случай», — то самое, что 🔐 Хранитель
#: данных имеет право заблокировать.
LIMIT_FIELDS: dict[str, str] = {
    "rateLimitType": "type",
    "status": "status",
    "resetsAt": "resets_at",
}

#: Всё, что вообще бывает в строке замера. Ни токенов, ни ключей, ни имён, ни
#: путей — по построению, а не по недосмотру.
SAMPLE_FIELDS: frozenset[str] = frozenset(
    {"ts", "session", *USAGE_FIELDS.values(), *LIMIT_FIELDS.values()}
)


class UnknownUsageFieldError(ValueError):
    """В `usage` пришло поле, которого нет в белом списке.

    Отдельный тип, а не общий отказ: вызывающему нужно отличить «реестр
    изменился, список пора пересмотреть» от «реестр отдал мусор».
    """

    def __init__(self, fields: list[str]) -> None:
        перечисление = ", ".join(sorted(fields))
        super().__init__(
            f"в usage незнакомые поля: {перечисление}. Возможно, это новые "
            "слагаемые расхода — записав замер без них, инструмент занизит "
            "сумму, и шкала будет неверной на неизвестную долю. Замер не "
            "пишется, пока поля не разобраны: см. src/claude_code_usage/"
            "whitelist.py и #7"
        )
        self.fields = sorted(fields)


def build_sample(
    session: dict[str, Any], *, ts: str, session_id: str
) -> dict[str, Any]:
    """Собрать строку замера из записи реестра по белому списку.

    Незнакомое поле вне ``usage`` отбрасывается молча — оно и не должно было
    попасть. Незнакомое поле внутри ``usage`` поднимает
    :class:`UnknownUsageFieldError`: замер не пишется.
    """
    usage = session.get("usage")
    limit = session.get("rate_limit_info")
    if not isinstance(usage, dict) or not isinstance(limit, dict):
        raise ValueError(
            "запись реестра без usage или rate_limit_info — замерять нечего. "
            "Тихая пустая строка отравила бы шкалу и обнаружилась бы через недели"
        )

    незнакомые = [поле for поле in usage if поле not in USAGE_FIELDS]
    if незнакомые:
        raise UnknownUsageFieldError(незнакомые)

    недостающие = sorted(set(USAGE_FIELDS) - set(usage))
    if недостающие:
        raise ValueError(
            f"в usage нет полей: {', '.join(недостающие)}. Замер из неполной "
            "суммы занизит расход, а дописать его потом не выйдет: хранилище "
            "append-only"
        )

    замер: dict[str, Any] = {"ts": ts, "session": session_id}
    for исходное, наше in LIMIT_FIELDS.items():
        замер[наше] = limit.get(исходное)
    for исходное, наше in USAGE_FIELDS.items():
        замер[наше] = usage[исходное]
    return замер


def audit(sample: dict[str, Any]) -> list[str]:
    """Что в замере лишнего. Пустой список — замер чист.

    Отдельная функция, а не проверка внутри сборки: она нужна и тому, кто
    читает **уже записанные** строки. Файл замеров переживает несколько версий
    инструмента, и строка, написанная старой, может нести поле, которого в
    белом списке больше нет.
    """
    return sorted(поле for поле in sample if поле not in SAMPLE_FIELDS)
