"""Свои потоки говорят UTF-8, а не то, что решила локаль (#69).

Копия функции из `scripts/utf8_output.py`, и копия намеренная. Свести их в
одно место нельзя ни в одну сторону:

* пакет не может импортировать `scripts/` — его ставят у чужого человека, где
  никаких `scripts/` нет;
* `scripts/` не может зависеть от пакета — четыре workflow (`changelog`,
  `merge-queue`, `pr-check`, `pr-metadata`) запускают скрипты **без установки**.

Значит общего дома у неё нет, и попытка его завести сломает либо установку
пакета, либо четыре прогона. Правило при этом одно, поэтому одинаково и имя:
гейт ищет вызов по имени, и разойтись копиям он не даст.

## Почему это вообще нужно

Вывод здесь русский, а кодировка потока по умолчанию берётся из локали. На
Windows она не UTF-8, и дальше по-разному:

* `stdout` (`errors="strict"`) падает с `UnicodeEncodeError` — видно;
* `stderr` (`errors="backslashreplace"`) **не падает**: причина отказа выходит
  как `\\u0445\\u0440\\u0430\\u043d\\u0438\\u043b\\u0438\\u0449\\u0435`.

Второе хуже, и здесь особенно: у скриптов такой отказ читает прогон, а у
пакета — человек, который его поставил. Команда формально отработала, код
возврата верный, а что делать дальше — непонятно.
"""

from __future__ import annotations

import sys


def force_utf8_output() -> None:
    """Заставить `stdout` и `stderr` этого процесса говорить UTF-8.

    Зовётся первым делом в `main`: до первой печати, иначе часть вывода уже
    ушла в локали. Поток без `reconfigure` (подменённый в тесте,
    перенаправленный) пропускается молча — это не отказ, а отсутствие предмета.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", errors="replace")
