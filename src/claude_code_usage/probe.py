"""Накопительный ли `usage` реестра: замер, сведённый к одной команде (#101).

Спецификация говорит «просуммировать по сессиям, попадающим в окно» и не
говорит главного — **что именно суммируется**: итог сессии или её приращение за
окно. Правил ровно два, и они дают разные числа:

**Если `usage` — итог сессии:** сессия старше окна вносит в сумму больше, чем
израсходовала внутри него; расход за окно считается **разностью двух замеров**;
по одному замеру его нет вовсе.

**Если `usage` — расход за текущее окно:** сумма по сессиям и есть расход за
окно, и одного замера достаточно.

Выбор неверного правила даёт цифру, которая выглядит правдоподобно и врёт, —
то, что роль метролога обязана блокировать.

## Что здесь решающее, а что нет

**Не решающее — рост между двумя замерами.** Он предсказывается ОБОИМИ
чтениями: и итог сессии, и расход за текущее окно растут, пока окно идёт.
Наблюдать его и делать вывод — та самая ошибка, от которой заведено правило 178.

**Решающее — поведение через СБРОС окна.** Если между замерами окно
сменилось — `resetsAt` стал другим, — то:

* расход **упал** → число относится к окну, суммируется напрямую;
* расход **вырос или не изменился** → это итог сессии, и расход за окно
  считается разностью.

Сброса между замерами не было — ответа нет, и он так и называется: третий исход,
а не «похоже на». Требовать вывод от данных, которые его не несут, — ровно то,
из-за чего вопрос и открыт.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from . import registry, whitelist

#: Токены, а не деньги: `cost_usd` — производная по чужой формуле, и её
#: поведение через сброс ничего не говорит о природе исходных чисел.
ТОКЕНЫ = tuple(
    имя for поле, имя in whitelist.USAGE_FIELDS.items() if поле != "cost_usd"
)

#: Три исхода, а не два (правило 039).
ЗА_ОКНО = "за окно"
ИТОГ_СЕССИИ = "итог сессии"
НЕ_РАЗЛИЧИТЬ = "не различить"


@dataclass(frozen=True)
class Сессия:
    """Одна сессия в двух замерах: сколько было, сколько стало, сменилось ли окно."""

    session: str
    было: int
    стало: int
    окно_сменилось: bool

    @property
    def упал(self) -> bool:
        return self.стало < self.было


@dataclass(frozen=True)
class Вердикт:
    """Ответ и **на чём он основан** — счёт, а не только слово.

    Погрешность называется вслух: сколько сессий сопоставлено, у скольких
    сменилось окно, сколько из них упало. Без этих чисел «за окно» неотличимо
    от «за окно, по одной сессии из ста».
    """

    ответ: str
    сопоставлено: int
    со_сбросом: int
    упало: int
    только_в_одном: int

    def __str__(self) -> str:
        основа = (
            f"сопоставлено сессий {self.сопоставлено}, "
            f"со сменой окна {self.со_сбросом}, из них упало {self.упало}; "
            f"только в одном замере {self.только_в_одном}"
        )
        if self.ответ == НЕ_РАЗЛИЧИТЬ:
            return (
                f"НЕ РАЗЛИЧИТЬ: {основа}. Между замерами окно ни у одной сессии "
                "не сменилось, а рост сам по себе предсказывается ОБОИМИ "
                "чтениями — вывод из него был бы догадкой. Нужен замер по обе "
                "стороны сброса: снять выгрузку, дождаться, когда resetsAt "
                "пройдёт, снять снова"
            )
        if self.ответ == ЗА_ОКНО:
            return (
                f"ЧИСЛО ЗА ОКНО: {основа}. Через сброс расход упал — значит "
                "usage относится к текущему окну и суммируется напрямую, "
                "одного замера достаточно"
            )
        return (
            f"ИТОГ СЕССИИ: {основа}. Через сброс расход не упал — значит usage "
            "накопительный, и расход за окно считается РАЗНОСТЬЮ двух замеров; "
            "по одному замеру его нет вовсе"
        )


def _расход(запись: dict[str, Any]) -> int:
    usage = запись.get("usage")
    if not isinstance(usage, dict):
        return 0
    итог = 0
    for поле, имя in whitelist.USAGE_FIELDS.items():
        if имя not in ТОКЕНЫ:
            continue
        значение = usage.get(поле)
        if isinstance(значение, int):
            итог += значение
    return итог


def _окно(запись: dict[str, Any]) -> Any:
    limit = запись.get("rate_limit_info")
    return limit.get("resetsAt") if isinstance(limit, dict) else None


def сессии(раньше: Any, позже: Any) -> list[Сессия]:
    """Сопоставить две выгрузки по сессиям.

    Сессия, которой нет в одной из выгрузок, в сравнение не идёт: у неё нет
    второй точки, и приписать ей поведение нечем.
    """
    первая = {з.session: з.payload for з in registry.records(раньше).records}
    вторая = {з.session: з.payload for з in registry.records(позже).records}
    общие = sorted(set(первая) & set(вторая))
    return [
        Сессия(
            session=имя,
            было=_расход(первая[имя]),
            стало=_расход(вторая[имя]),
            окно_сменилось=_окно(первая[имя]) != _окно(вторая[имя]),
        )
        for имя in общие
    ]


def сравнить(раньше: Any, позже: Any) -> Вердикт:
    """Вынести вердикт по двум выгрузкам реестра."""
    пары = сессии(раньше, позже)
    первая = {з.session for з in registry.records(раньше).records}
    вторая = {з.session for з in registry.records(позже).records}
    только_в_одном = len(первая ^ вторая)

    со_сбросом = [п for п in пары if п.окно_сменилось]
    упало = [п for п in со_сбросом if п.упал]

    if not со_сбросом:
        ответ = НЕ_РАЗЛИЧИТЬ
    elif упало:
        ответ = ЗА_ОКНО
    else:
        ответ = ИТОГ_СЕССИИ

    return Вердикт(
        ответ=ответ,
        сопоставлено=len(пары),
        со_сбросом=len(со_сбросом),
        упало=len(упало),
        только_в_одном=только_в_одном,
    )
