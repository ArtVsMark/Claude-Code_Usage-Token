def test_значка_версии_в_дереве_нет() -> None:
    """Значок уехал на ветку `badges`, и в общей ветке его быть не должно.

    Прежняя редакция читала файл из дерева и сверяла с источником. После
    переезда предмета не стало: сверку «собранное совпадает с источником»
    делает `tests/test_badges.py`, а здесь проверяется обратное — что общая
    ветка значков не носит.

    Тест написан по НАСТОЯЩЕМУ отказу: локально он был зелёным, потому что
    файл лежал на диске неотслеживаемым (его собрал сборщик), а в прогоне
    после checkout его нет. Зелёное было на состоянии, которого в CI не
    бывает (правило 018).
    """
    assert preflight.expected_badge("version", КОРЕНЬ) is not None, (
        "правило вывода обязано существовать и после переезда"
    )
    assert not (КОРЕНЬ / ".github" / "badges" / "version.json").exists()


