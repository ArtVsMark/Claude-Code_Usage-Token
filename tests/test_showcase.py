def test_замечание_не_меняет_код_возврата(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """Главное требование #11, проверенное на самом `main`, а не на отчёте.

    Расхождение витрин — состояние документации, а не дефект кода. Смешать его
    с отказами значило бы либо останавливать коммит из-за перевода, либо
    приучить пропускать красное.

    Список проверок подменён пустым: иначе `main` запустил бы `pytest`, то есть
    сам этот тест.

    Контракт витрины заведён исправным намеренно: проверяется, что замечание не
    красит прогон, а не то, что рядом ничего не сломано.
    """
    _контракт(tmp_path, ru=_ВИТРИНА_RU, en=_ВИТРИНА_EN + "\nНепереведено.\n")
    monkeypatch.setattr(preflight, "ROOT", tmp_path)
    monkeypatch.setattr(preflight, "checks", tuple)
    monkeypatch.setattr(preflight, "tracked_files", list)

    код = preflight.main([])

    вывод = capsys.readouterr().err
    assert код == 0, "замечание не должно превращаться в отказ"
    assert "~ паритет витрин" in вывод
    assert "замечаний" in вывод, "число замечаний обязано быть в выводе"
    # Не «замечаний 1»: во временном дереве нет git-тегов, и счёт версии
    # добавляет своё замечание — законное и по тому же правилу 039. Привязка к
    # точному числу ловила бы появление ЛЮБОГО второго замечания, а тест не про
    # это.


def test_отказ_остаётся_отказом_рядом_с_замечанием() -> None:
    """Замечание не должно и заглушать отказ."""
    итог = preflight.report(["mypy"], [("ruff check", "E501")], ["паритет витрин: 1"])
    assert "не прошло: ruff check" in итог
    assert "~ паритет витрин" in итог
    assert "замечаний 1" in итог


# ── контракт витрины ──────────────────────────────────────────────────────
#
# У проверяющего инструмента две ошибки, и они несимметричны. Ложное «прошло» —
# приняли витрину, которая не отвечает: пробел не назван, а выглядит как ответ.
# Ложное «не прошло» — завернули верное: гейт краснеет на законном случае, и
# первой же правкой его выключают вместе со всем, что он ловил.
#
# Поэтому здесь на каждую находку по два теста: подделанный набор обязан
# находиться, законный — проходить.

#: Вопрос без предмета: минимальный законный ответ. Причина длиннее порога —
#: короткая причина проверяется отдельным тестом.
ПРОБЕЛ: dict[str, Any] = {
    "id": "pypi",
    "ask": "какая версия опубликована в PyPI",
    "absent": "предмета нет: дистрибутив не публиковался ни разу",
}

_ВИТРИНА_RU = "# Заголовок\n\nНабор: [.rules/showcase.json](.rules/showcase.json)\n"
_ВИТРИНА_EN = "# Title\n\nSet: [.rules/showcase.json](.rules/showcase.json)\n"


def _контракт(
    каталог: Path,
    вопросы: list[dict[str, Any]] | None = None,
    ru: str = _ВИТРИНА_RU,
    en: str = _ВИТРИНА_EN,
) -> Path:
    """Отдельное дерево с набором вопросов и обеими витринами."""
    _файл(
        каталог,
        preflight.SHOWCASE_SET,
        json.dumps(
            {"schema": "1.0", "questions": [ПРОБЕЛ] if вопросы is None else вопросы},
            ensure_ascii=False,
        ),
    )
    _витрины(каталог, ru, en)
    # Гейт имён shell отказывает на дереве без workflow — проверке нужен
    # предмет. Здесь он заведён исправным намеренно: тесты ниже про витрину, а
    # не про то, что рядом ничего не сломано. Событие `pull_request` и группа
    # отмены с головой — по той же причине: без них остаётся без предмета гейт
    # `concurrency_head`, а с группой без головы он краснеет.
    _файл(
        каталог,
        ".github/workflows/example.yml",
        "name: пример\n"
        "on:\n"
        "  pull_request:\n"
        "concurrency:\n"
        "  group: x-${{ github.event.pull_request.head.sha }}\n"
        "  cancel-in-progress: true\n"
        "jobs:\n"
        "  x:\n"
        "    steps:\n"
        "      - run: files=1\n",
    )
    # Ответ каталогу правил — по той же причине: гейт `rules_answer` отказывает
    # на дереве без него, потому что молчание вместо ответа неотличимо от
    # согласия со всеми правилами сразу.
    _файл(
        каталог,
        ".rules/bindings.json",
        json.dumps(
            {
                "schema": "1.1",
                "project": "Владелец/Проект",
                "rules": {"001": {"status": "unreviewed"}},
            },
            ensure_ascii=False,
        ),
    )
    return каталог


def _источник_версии(каталог: Path, версия: str = "1.2.3") -> None:
    """Разложить то, откуда гейт берёт версию.

    Путь к источнику читается из `pyproject.toml`, а сама версия — из
    названного там файла. Двух мест, где лежит одно знание, здесь быть не
    должно — ни в продукте, ни в подделке.
    """
    _файл(
        каталог,
        "pyproject.toml",
        '[project]\ndynamic = ["version"]\n\n'
        '[tool.hatch.version]\npath = "src/pkg/__init__.py"\n',
    )
    _файл(каталог, "src/pkg/__init__.py", f'__version__ = "{версия}"\n')


def _со_значком(
    каталог: Path,
    версия: str = "1.2.3",
    сообщение: str | None = None,
    вопрос: dict[str, Any] | None = None,
) -> Path:
    """Дерево, в котором объявлен и разложен живой значок версии."""
    объявление: dict[str, Any] = вопрос or {
        "id": "version",
        "ask": "какая версия у текущей головы",
        "badge": ".github/badges/version.json",
    }
    показ = "Значок: version.json\n"
    _контракт(каталог, [ПРОБЕЛ, объявление], _ВИТРИНА_RU + показ, _ВИТРИНА_EN + показ)
    _источник_версии(каталог, версия)
    _файл(
        каталог,
        ".github/badges/version.json",
        json.dumps(
            {
                "schemaVersion": 1,
                "label": "version",
                "message": версия if сообщение is None else сообщение,
                "color": preflight.BADGE_COLOR,
            }
        ),
    )
    return каталог


