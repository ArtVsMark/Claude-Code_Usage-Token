# ── «предмета нет» — утверждение, а не оборот речи ─────────────────────────
#
# Проза в `absent` непроверяема, и гейт её не трогает. Но у неё есть подкласс,
# который проверяется механически: заявление о том, что предмета не существует,
# когда существование предмета видно из дерева. Ровно на нём витрина и соврала
# — ответ «проект не выпускался ни разу» пережил два выпуска (#59).


def _дерево_с_тегом(каталог: Path, тег: str | None) -> Path:
    """Дерево под версией, при желании с тегом выпуска."""
    subprocess.run(["git", "init", "-q"], cwd=каталог, check=True, timeout=30)
    _файл(каталог, "файл.txt", "содержимое\n")
    subprocess.run(["git", "add", "."], cwd=каталог, check=True, timeout=30)
    subprocess.run(
        [
            "git",
            "-c",
            "user.email=к@т",
            "-c",
            "user.name=тест",
            "commit",
            "-qm",
            "нить",
        ],
        cwd=каталог,
        check=True,
        timeout=30,
    )
    if тег is not None:
        subprocess.run(["git", "tag", тег], cwd=каталог, check=True, timeout=30)
    return каталог


