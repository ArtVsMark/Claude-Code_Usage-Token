def test_значок_с_отдельной_ветки_не_требует_файла(tmp_path: Path) -> None:
    """Ложное «не прошло», которое напрашивается само.

    Значок, объявленный на отдельной ветке, в этом дереве не лежит и лежать не
    должен: ветка заводится ровно для того, чтобы пересборка значка не двигала
    общую. Требовать файл здесь значило бы заворачивать верное.

    Вопрос взят с СУЩЕСТВУЮЩИМ правилом вывода. Прежняя редакция брала
    `coverage`, которого гейт считать не умеет, и была зелёной по обеим
    причинам сразу — а значит не различала их.
    """
    корень = _контракт(
        tmp_path,
        [
            ПРОБЕЛ,
            {
                "id": "version",
                "ask": "какая версия у текущей головы",
                "badge": ".github/badges/version.json",
                "branch": "badges",
            },
        ],
        _ВИТРИНА_RU + "Значок: version.json\n",
        _ВИТРИНА_EN + "Значок: version.json\n",
    )
    # Источник версии нужен: правило вывода проверяется независимо от ветки.
    # Файла значка при этом НЕТ намеренно — в том и проверка.
    _источник_версии(корень)

    assert preflight.check_showcase(корень).findings == []
    assert not (корень / ".github/badges/version.json").exists()


