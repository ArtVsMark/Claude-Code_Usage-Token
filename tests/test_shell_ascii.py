"""Проверки гейта на не-ASCII имена в shell (#34).

Ошибка, ради которой заведён гейт, проявляется двумя способами, и почти все
проверки здесь — про **второй**: переменная окружения с кириллическим именем
создаётся штатно, `$имя` не раскрывается, условие всегда даёт одну ветку, и
проверка остаётся зелёной, ничего не проверив.

Первый способ — падение с кодом 127 — чинится сам собой: красное видно.
"""

from __future__ import annotations

from pathlib import Path

import shell_ascii

КОРЕНЬ = Path(__file__).resolve().parents[1]

ЧИСТЫЙ = """\
name: пример
on:
  pull_request:
jobs:
  gates:
    name: гейты
    steps:
      - name: собрать список изменённых файлов
        env:
          PR_LABELS: ${{ join(github.event.pull_request.labels.*.name, ' ') }}
        run: |
          set -euo pipefail
          files=$(git diff --name-only "$BASE_SHA...$HEAD_SHA")
          echo "изменённых файлов: $files"
          case " $PR_LABELS " in
            *" bug "*) required=yes ;;
          esac
"""


def _находки(текст: str) -> list[str]:
    return [f.message for f in shell_ascii.check_text(текст, "пример.yml")]


# ── подделанное находится ─────────────────────────────────────────────────


def test_присваивание_кириллицей_находится() -> None:
    """`файлы=$(…)` bash разбирает как имя команды: код возврата 127."""
    сломанный = ЧИСТЫЙ.replace(
        "          files=$(git diff", "          файлы=$(git diff"
    )

    находки = _находки(сломанный)

    assert any("файлы=" in н for н in находки)
    assert any("127" in н for н in находки)


def test_ключ_env_кириллицей_находится() -> None:
    """Самый опасный случай: гейт останется зелёным, не проверив ничего."""
    сломанный = ЧИСТЫЙ.replace("PR_LABELS:", "МЕТКИ:")

    находки = _находки(сломанный)

    assert any("env" in н and "МЕТКИ" in н for н in находки)
    assert any("молча" in н for н in находки)


def test_подстановка_кириллицей_находится() -> None:
    сломанный = ЧИСТЫЙ.replace('" $PR_LABELS "', '" $МЕТКИ "')

    находки = _находки(сломанный)

    assert any("не раскроется" in н for н in находки)


def test_фигурная_подстановка_находится() -> None:
    сломанный = ЧИСТЫЙ.replace('"$BASE_SHA...$HEAD_SHA"', '"${начало}...${конец}"')

    находки = _находки(сломанный)

    assert len([н for н in находки if "не раскроется" in н]) == 2


def test_однострочный_run_проверяется() -> None:
    """Тело `run:` бывает на той же строке, и пропустить его нельзя."""
    находки = _находки("jobs:\n  x:\n    steps:\n      - run: результат=$(echo 1)\n")

    assert any("результат=" in н for н in находки)


def test_пустая_строка_не_обрывает_блок() -> None:
    """`run:` из двух абзацев — обычное дело, и второй тоже shell.

    Оборвись блок на пустой строке — гейт проверял бы только первый абзац и
    молчал бы обо всём, что написано после отбивки.
    """
    текст = (
        "jobs:\n  x:\n    steps:\n      - run: |\n"
        "          set -euo pipefail\n"
        "\n"
        "          итог=$(echo 1)\n"
    )

    assert any("итог=" in н for н in _находки(текст))


def test_переменная_цикла_находится() -> None:
    """`for попытка in …` — тоже объявление, но на присваивание не похоже.

    Найдено этим же гейтом в собственном `release.yml`: пять попыток дождаться
    индекса писались как `for попытка in 1 2 3 4 5`, и первая редакция гейта
    строку пропустила — она проверяла только `имя=`.
    """
    текст = (
        "jobs:\n  x:\n    steps:\n      - run: |\n"
        "          for попытка in 1 2 3; do echo $попытка; done\n"
    )

    находки = _находки(текст)

    assert any("переменная цикла" in н for н in находки)


def test_переменная_чтения_находится() -> None:
    текст = "jobs:\n  x:\n    steps:\n      - run: |\n          read -r строка\n"

    assert any("переменная чтения" in н for н in _находки(текст))


def test_латинская_переменная_цикла_проходит() -> None:
    текст = (
        "jobs:\n  x:\n    steps:\n      - run: |\n"
        "          for attempt in 1 2 3; do echo \"попытка $attempt\"; done\n"
    )

    assert _находки(текст) == []


# ── верное не заворачивается ──────────────────────────────────────────────


def test_чистый_workflow_проходит() -> None:
    assert _находки(ЧИСТЫЙ) == []


def test_проза_не_трогается() -> None:
    """Правило про идентификаторы, а не про язык.

    Комментарии, `name:` и тексты `echo` остаются русскими — иначе гейт
    потребовал бы перевести проект, а не починить имя переменной.
    """
    текст = ЧИСТЫЙ.replace(
        '          echo "изменённых файлов: $files"',
        '          echo "изменённых файлов: $files" # считаем охват\n'
        '          echo "ключ=значение и знак $ сам по себе"',
    )

    assert _находки(текст) == []


def test_выражения_площадки_не_находка() -> None:
    """`${{ … }}` — синтаксис площадки, а не подстановка bash."""
    assert (
        _находки('jobs:\n  x:\n    steps:\n      - run: echo "${{ github.событие }}"\n')
        == []
    )


def test_комментарий_с_присваиванием_не_находка() -> None:
    текст = (
        "jobs:\n  x:\n    steps:\n      - run: |\n"
        "          # первая редакция писала файлы=$(git diff …) и падала\n"
        "          files=1\n"
    )

    assert [н for н in _находки(текст) if "присваивание" in н] == []


# ── живое дерево ──────────────────────────────────────────────────────────


def test_живые_workflow_проекта_проходят() -> None:
    assert shell_ascii.check_workflows(КОРЕНЬ) == []


def test_без_workflow_гейт_отказывает(tmp_path: Path) -> None:
    """Проверка, не нашедшая предмета, обязана сказать об этом.

    Переезд каталога иначе отключил бы гейт молча, и он остался бы зелёным
    навсегда.
    """
    (tmp_path / ".github" / "workflows").mkdir(parents=True)

    находки = shell_ascii.check_workflows(tmp_path)

    assert len(находки) == 1
    assert "без предмета" in находки[0].message
