"""Две копии `force_utf8_output` совпадают телом (правило 214, #141).

Копии подписаны и намеренны: пакет не может импортировать `scripts/`, а
`scripts/` запускаются без установки пакета. Обе шапки при этом утверждали,
что разойтись копиям «не даёт гейт», — но гейт ищет вызов по имени, а тела не
сверял никто. Сверяет этот тест: синтаксическое дерево тела без строки
документации. Документация разная законно — перенос строк в ней свой.
"""

from __future__ import annotations

import ast
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
КОПИИ = ("scripts/utf8_output.py", "src/claude_code_usage/output.py")
ИМЯ = "force_utf8_output"


def тело(исходник: str, имя: str = ИМЯ) -> str:
    """Дамп тела функции без строки документации; пусто, если функции нет."""
    for узел in ast.walk(ast.parse(исходник)):
        if isinstance(узел, ast.FunctionDef) and узел.name == имя:
            операторы = узел.body
            if (
                операторы
                and isinstance(операторы[0], ast.Expr)
                and isinstance(операторы[0].value, ast.Constant)
            ):
                операторы = операторы[1:]
            return "\n".join(ast.dump(о) for о in операторы)
    return ""


def test_копии_совпадают_телом() -> None:
    тела = {путь: тело((КОРЕНЬ / путь).read_text(encoding="utf-8")) for путь in КОПИИ}
    assert all(тела.values()), f"функции {ИМЯ} нет в одной из копий: {КОПИИ}"
    assert len(set(тела.values())) == 1, f"копии {ИМЯ} разошлись: {КОПИИ}"


def test_сверка_видит_расхождение_и_пропускает_документацию() -> None:
    исходная = 'def f():\n    """А."""\n    x = 1\n'
    другая_документация = 'def f():\n    """Б, и длиннее."""\n    x = 1\n'
    другое_тело = 'def f():\n    """А."""\n    x = 2\n'

    assert тело(исходная, "f") == тело(другая_документация, "f")
    assert тело(исходная, "f") != тело(другое_тело, "f")
