"""Накопительный ли `usage` реестра (#101).

Дороже всего здесь **вывод из роста**. Он предсказывается ОБОИМИ чтениями — и
итог сессии, и расход за текущее окно растут, пока окно идёт, — поэтому «выросло
значит накопительный» это догадка, а не замер (правило 178). Решающее
наблюдение одно: поведение ЧЕРЕЗ сброс окна.

Поэтому главный тест здесь — тот, где ответа НЕТ: «не различить» обязано быть
полноценным исходом, а не неудачей, иначе команда будет отвечать на данных,
которые ответа не несут.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from claude_code_usage import cli, probe


def _сессия(имя: str, токенов: int, окно: str) -> dict[str, Any]:
    return {
        "id": имя,
        "usage": {
            "input_tokens": токенов,
            "output_tokens": 0,
            "cache_read_tokens": 0,
            "cache_write_tokens": 0,
            "cost_usd": 0.0,
        },
        "rate_limit_info": {
            "rateLimitType": "five_hour",
            "status": "allowed",
            "resetsAt": окно,
        },
    }


ОКНО_1 = "2026-09-07T15:00:00Z"
ОКНО_2 = "2026-09-07T20:00:00Z"


# ── решающее наблюдение ─────────────────────────────────────────────────────


def test_через_сброс_упало_значит_за_окно() -> None:
    вердикт = probe.сравнить([_сессия("s1", 900, ОКНО_1)], [_сессия("s1", 120, ОКНО_2)])
    assert вердикт.ответ == probe.ЗА_ОКНО
    assert вердикт.со_сбросом == 1
    assert "суммируется напрямую" in str(вердикт)


def test_через_сброс_не_упало_значит_итог_сессии() -> None:
    вердикт = probe.сравнить(
        [_сессия("s1", 900, ОКНО_1)], [_сессия("s1", 1400, ОКНО_2)]
    )
    assert вердикт.ответ == probe.ИТОГ_СЕССИИ
    assert "РАЗНОСТЬЮ двух замеров" in str(вердикт)


# ── третий исход ────────────────────────────────────────────────────────────


def test_рост_без_сброса_ответа_не_даёт() -> None:
    """Главный тест набора: рост предсказывают ОБА чтения.

    Команда, отвечающая здесь «накопительный», отвечала бы на данных, которые
    ответа не несут, — и её цифра выглядела бы правдоподобно и врала.
    """
    вердикт = probe.сравнить(
        [_сессия("s1", 900, ОКНО_1)], [_сессия("s1", 1400, ОКНО_1)]
    )
    assert вердикт.ответ == probe.НЕ_РАЗЛИЧИТЬ
    assert вердикт.со_сбросом == 0
    assert "resetsAt" in str(вердикт)


def test_совпадающих_сессий_нет() -> None:
    вердикт = probe.сравнить([_сессия("s1", 900, ОКНО_1)], [_сессия("s2", 100, ОКНО_2)])
    assert вердикт.ответ == probe.НЕ_РАЗЛИЧИТЬ
    assert вердикт.сопоставлено == 0
    assert вердикт.только_в_одном == 2


# ── погрешность названа вслух ───────────────────────────────────────────────


def test_вердикт_называет_на_чём_основан() -> None:
    """«За окно» без чисел неотличимо от «за окно, по одной сессии из ста»."""
    вердикт = probe.сравнить(
        [_сессия("s1", 900, ОКНО_1), _сессия("s2", 50, ОКНО_1)],
        [_сессия("s1", 120, ОКНО_2), _сессия("s2", 50, ОКНО_1)],
    )
    текст = str(вердикт)
    assert "сопоставлено сессий 2" in текст
    assert "со сменой окна 1" in текст
    assert "из них упало 1" in текст


def test_деньги_в_счёт_не_идут() -> None:
    """`cost_usd` — производная по чужой формуле, и разложить её нечем."""
    assert "cost_usd" not in probe.ТОКЕНЫ


# ── команда ─────────────────────────────────────────────────────────────────


def _файл(каталог: Path, имя: str, данные: Any) -> str:
    путь = каталог / имя
    путь.write_text(json.dumps(данные), encoding="utf-8")
    return str(путь)


def test_команда_печатает_вердикт(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    до = _файл(tmp_path, "до.json", [_сессия("s1", 900, ОКНО_1)])
    после = _файл(tmp_path, "после.json", [_сессия("s1", 120, ОКНО_2)])
    assert cli.main(["probe", "--before", до, "--after", после]) == 0
    assert "ЧИСЛО ЗА ОКНО" in capsys.readouterr().out


def test_команда_не_пишет_в_хранилище(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Проба отвечает на вопрос спецификации, а не снимает замер."""
    до = _файл(tmp_path, "до.json", [_сессия("s1", 900, ОКНО_1)])
    после = _файл(tmp_path, "после.json", [_сессия("s1", 120, ОКНО_2)])
    cli.main(["probe", "--before", до, "--after", после])
    assert list(tmp_path.glob("*.jsonl")) == []


def test_нечитаемая_выгрузка_это_отказ_вызова(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (tmp_path / "битая.json").write_text("не json", encoding="utf-8")
    код = cli.main(
        [
            "probe",
            "--before",
            str(tmp_path / "битая.json"),
            "--after",
            str(tmp_path / "битая.json"),
        ]
    )
    assert код == cli.EXIT_USAGE
    assert "не прочитана" in capsys.readouterr().err
