"""Объявленный исход механизма используется, а не только объявлен (#151).

Константа `EXIT_*`, которую модуль объявил и ни разу не вернул, — обещание
третьего исхода, которого нет: читатель видит `EXIT_BROKEN = 2` и считает, что
«не отработал» отличён от находки, а скрипт уходит с кодом 1. Аудит #139
нашёл четыре такие константы, и ни одна проверка их не видела.

Форма взята у проекта механизмов (`tests/outcomes.py`, реестр исходов) и
упрощена до первой ступени: там каждый объявленный исход обязан быть ещё и
УТВЕРЖДЁН набором тестов, здесь — хотя бы прочитан модулем. Тест, а не
отдельный скрипт, — чтобы при переезде на их конвейер (#158) он уехал вместе
с набором, а не переписывался.
"""

import ast
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]

#: Где живут механизмы с кодами возврата.
ПРЕДМЕТ = ("scripts", ".claude/hooks", "src/claude_code_usage")


def объявленные(дерево: ast.Module) -> set[str]:
    """Имена `EXIT_*`, присвоенные на верхнем уровне модуля."""
    имена: set[str] = set()
    for узел in дерево.body:
        цели = узел.targets if isinstance(узел, ast.Assign) else []
        if isinstance(узел, ast.AnnAssign):
            цели = [узел.target]
        for цель in цели:
            if isinstance(цель, ast.Name) and цель.id.startswith("EXIT_"):
                имена.add(цель.id)
    return имена


def прочитанные(дерево: ast.Module) -> set[str]:
    """Имена, которые модуль где-то читает, а не только присваивает."""
    return {
        узел.id
        for узел in ast.walk(дерево)
        if isinstance(узел, ast.Name) and isinstance(узел.ctx, ast.Load)
    }


def модули() -> list[Path]:
    return sorted(
        путь
        for каталог in ПРЕДМЕТ
        for путь in (КОРЕНЬ / каталог).glob("*.py")
        if путь.is_file()
    )


def test_предмет_есть() -> None:
    """Проверка без предмета зеленела бы на пустоте (правило 075)."""
    объявивших = [
        путь
        for путь in модули()
        if объявленные(ast.parse(путь.read_text(encoding="utf-8")))
    ]
    assert len(объявивших) >= 10, объявивших


def test_каждый_объявленный_исход_используется() -> None:
    мёртвые = []
    for путь in модули():
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
        for имя in sorted(объявленные(дерево) - прочитанные(дерево)):
            мёртвые.append(f"{путь.relative_to(КОРЕНЬ).as_posix()}::{имя}")
    assert not мёртвые, (
        "объявлен и ни разу не используется: " + ", ".join(мёртвые) + ". Либо "
        "исход настоящий и его надо вернуть там, где он наступает, либо его нет — "
        "и тогда константа обещает то, чего скрипт не делает"
    )


def test_проверка_видит_мёртвый_исход() -> None:
    """Обе половины предиката на подделке: мёртвый — виден, живой — нет."""
    мёртвый = ast.parse(
        "EXIT_OK = 0\nEXIT_BROKEN = 2\ndef main():\n    return EXIT_OK\n"
    )
    assert объявленные(мёртвый) - прочитанные(мёртвый) == {"EXIT_BROKEN"}

    живой = ast.parse("EXIT_BROKEN: int = 2\ndef main():\n    return EXIT_BROKEN\n")
    assert объявленные(живой) - прочитанные(живой) == set()
