"""Чтение кода возврата чужого скрипта во «входящих» (#102, #125).

До v1.4.0 каталога скрипт `link_trails.py` отвечал тремя исходами по двум
кодам: с `--apply` единица значила «недостающие были и все дописаны», то есть
удачу, и прогон здесь держал обёртку, принимавшую её вместе с напечатанным
«дописано». Инцидент уехал каталогу и починен у него (правило 186): теперь
считается ОСТАТОК после записи, и при `--apply` исходов два — 0 или 2.

Поэтому обёртка снята, и проверяется обратное: код проходит наружу **как
есть**. Оставленное «смягчение» единицы было бы второй редакцией смысла — и
единственным местом, где настоящий отказ мог бы стать зелёным.

Проверяется **поведение**, а не текст: блок `run:` вынимается из workflow и
**исполняется** с подделанным `python` в `PATH`. Сверка «в файле есть нужные
слова» здесь ничего не стоила бы — сломать поведение можно, не тронув ни одного
из них (`|| true` в конце), и такая сверка осталась бы зелёной.
"""

import re
import shutil
import subprocess
import textwrap
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
WORKFLOW = КОРЕНЬ / ".github" / "workflows" / "rules-inbox.yml"
ШАГ = "обратные ссылки на правила в задачах"

BASH = shutil.which("bash")
нужен_bash = pytest.mark.skipif(BASH is None, reason="блок run: исполняется bash'ем")


def _блок_run() -> str:
    """Вынуть тело `run: |` у шага обратных ссылок, сняв отступ YAML."""
    текст = WORKFLOW.read_text(encoding="utf-8")
    после_шага = текст.split(f"name: {ШАГ}", 1)
    assert len(после_шага) == 2, f"шаг «{ШАГ}» в {WORKFLOW.name} не найден"
    хвост = после_шага[1]

    начало = re.search(r"^(\s*)run: \|\s*$", хвост, re.MULTILINE)
    assert начало is not None, "у шага нет блока `run: |`"
    отступ = len(начало.group(1)) + 2

    строки: list[str] = []
    for строка in хвост[начало.end() :].splitlines()[1:]:
        if строка.strip() and not строка.startswith(" " * отступ):
            break
        строки.append(строка)
    return textwrap.dedent("\n".join(строки))


def _прогнать(tmp_path: Path, *, вывод: str, код: int) -> int:
    """Исполнить блок `run:`, подставив вместо `python` подделку."""
    подделка = tmp_path / "python"
    # Разделитель heredoc — ASCII: имена и токены в shell только латиницей
    # (#34), а `dash` на не-ASCII разделителе рвёт первый же байт вывода.
    подделка.write_text(
        f"#!/bin/sh\ncat <<'EOF'\n{вывод}\nEOF\nexit {код}\n",
        encoding="utf-8",
    )
    подделка.chmod(0o755)

    assert BASH is not None
    итог = subprocess.run(
        [BASH, "-e", "-o", "pipefail", "-c", _блок_run()],
        cwd=tmp_path,
        env={"PATH": f"{tmp_path}:/usr/bin:/bin", "HOME": str(tmp_path)},
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=30,
    )
    return итог.returncode


ДОПИСАНО = "задач со следом: 12; без обратной ссылки было: 4 — дописано 4"
НЕЧЕГО = "задач со следом: 12; без обратной ссылки было: 0"


@нужен_bash
def test_дописано_это_код_ноль(tmp_path: Path) -> None:
    """С v1.4.0 удачная запись отвечает нулём — и он остаётся нулём."""
    assert _прогнать(tmp_path, вывод=ДОПИСАНО, код=0) == 0


@нужен_bash
def test_дописывать_было_нечего(tmp_path: Path) -> None:
    assert _прогнать(tmp_path, вывод=НЕЧЕГО, код=0) == 0


@нужен_bash
def test_единица_больше_не_смягчается(tmp_path: Path) -> None:
    """Даже рядом со словом «дописано»: при `--apply` единицы быть не должно.

    Появилась — значит скрипт снова сменил смысл кода, и это надо увидеть
    красным, а не принять по старой памяти.
    """
    assert _прогнать(tmp_path, вывод=ДОПИСАНО, код=1) == 1


@нужен_bash
def test_отказ_трекера_не_проглатывается(tmp_path: Path) -> None:
    """Код 2 — «не отработал»; проглотить его дороже всего."""
    assert (
        _прогнать(tmp_path, вывод="не отработал: запись в #63 не принята", код=2) == 2
    )


@нужен_bash
def test_падение_скрипта_не_проглатывается(tmp_path: Path) -> None:
    """Любой посторонний код проходит наружу как есть."""
    assert _прогнать(tmp_path, вывод="Traceback (most recent call last):", код=3) == 3


def test_запись_включена() -> None:
    """Умолчание скрипта сухое: без `--apply` шаг не пишет ничего и зеленеет."""
    assert "--apply" in _блок_run()
