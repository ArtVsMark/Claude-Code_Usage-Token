def test_пустая_перепись_это_отказ(tmp_path: Path) -> None:
    """Пустая отвечает «исключительных утверждений нет» — это утверждение."""
    корень = _дерево(tmp_path, [])
    находки = exclusive_claims.проверить(корень).находки
    assert len(находки) == 1
    assert "ни одного утверждения" in находки[0]


def test_чужая_версия_формата_не_разбирается(tmp_path: Path) -> None:
    """Подъём версии — повод перечитать, а не разобрать как получится (157)."""
    корень = _дерево(tmp_path, [{"subject": "x", "document": "свод.md", "claim": "y"}])
    файл = корень / exclusive_claims.ПЕРЕПИСЬ
    данные = json.loads(файл.read_text(encoding="utf-8"))
    данные["schema"] = "2.0"
    файл.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
    находки = exclusive_claims.проверить(корень).находки
    assert len(находки) == 1
    assert "версия формата" in находки[0]


def test_переписи_нет_это_воздержание(tmp_path: Path) -> None:
    """Файла нет — сверять нечего, и это НЕ то же, что пустая перепись.

    Пустая отвечает «исключительных утверждений в проекте нет» — утверждение о
    действительности. Отсутствие файла означает «этот проект переписи не
    ведёт», и краснеть на нём значило бы требовать её от любого дерева.

    Тихого разоружения это не даёт: адрес переписи назван в ответе каталогу, а
    `rules_answer` отвергает адрес, которого в дереве нет.
    """
    итог = exclusive_claims.проверить(tmp_path)
    assert итог.находки == []
    assert итог.переписи_нет is True
    assert exclusive_claims.main([str(tmp_path)]) == 0


def test_битая_перепись_это_отказ(tmp_path: Path) -> None:
    """А вот нечитаемый файл — отказ: он есть и он негоден."""
    (tmp_path / ".rules").mkdir()
    (tmp_path / exclusive_claims.ПЕРЕПИСЬ).write_text("не json", encoding="utf-8")
    находки = exclusive_claims.проверить(tmp_path).находки
    assert len(находки) == 1
    assert "не прочитана" in находки[0]


