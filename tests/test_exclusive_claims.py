"""Перепись исключительных утверждений (правило 181 каталога).

Дороже всего здесь **пропуск второго утверждения об уже занятом предмете**:
ровно от него правило и заведено, а последствие его — не поломка, а два
указания, каждое из которых запрещает второе. Читатель исполняет то, до
которого дочитал, и оба перестают действовать.

Второе по цене — **отставшая перепись**: утверждение объявлено, а в документе
его больше нет. Такое обнаруживается только в споре, то есть в худший момент.

Поэтому почти всё ниже — про отказы: удачный путь виден по любому прогону.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

import exclusive_claims

КОРЕНЬ = Path(__file__).resolve().parents[1]


def _дерево(tmp_path: Path, утверждения: list[dict[str, str]], **свод: str) -> Path:
    """Подделочное дерево: перепись и документы под ней."""
    (tmp_path / ".rules").mkdir(parents=True, exist_ok=True)
    (tmp_path / exclusive_claims.ПЕРЕПИСЬ).write_text(
        json.dumps(
            {"schema": exclusive_claims.СХЕМА, "claims": утверждения},
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    for имя, текст in свод.items():
        (tmp_path / f"{имя}.md").write_text(текст, encoding="utf-8")
    return tmp_path


# ── своё дерево ─────────────────────────────────────────────────────────────


def test_перепись_проекта_сходится_с_деревом() -> None:
    """Обещание переписи — про это дерево, и здесь оно выполняется."""
    итог = exclusive_claims.проверить(КОРЕНЬ)
    assert итог.находки == []
    assert итог.утверждений > 0


# ── занятый предмет ─────────────────────────────────────────────────────────


def test_два_утверждения_об_одном_предмете_отказ(tmp_path: Path) -> None:
    """Тот самый случай: каждое запрещает второе, и оба перестают действовать."""
    корень = _дерево(
        tmp_path,
        [
            {
                "subject": "где живёт состояние",
                "document": "свод.md",
                "claim": "только в задаче",
            },
            {
                "subject": "где живёт состояние",
                "document": "свод.md",
                "claim": "только в реестре",
            },
        ],
        свод="только в задаче\nи ещё только в реестре\n",
    )
    находки = exclusive_claims.проверить(корень).находки
    assert len(находки) == 1
    assert "занят" in находки[0]


def test_разные_предметы_живут_рядом(tmp_path: Path) -> None:
    """Правило про один предмет, а не про число исключительных утверждений."""
    корень = _дерево(
        tmp_path,
        [
            {"subject": "транспорт", "document": "свод.md", "claim": "только REST"},
            {"subject": "хранилище", "document": "свод.md", "claim": "только git"},
        ],
        свод="только REST и только git\n",
    )
    assert exclusive_claims.проверить(корень).находки == []


