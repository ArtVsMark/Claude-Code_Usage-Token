"""Исключительное утверждение принадлежит документу, а не разделу (правило 181).

«X читают **только** отсюда», «единственный источник Y — Z» связывает **весь**
документ. Два таких утверждения об одном предмете друг друга не уточняют:
каждое запрещает второе, и оба перестают действовать — читатель исполняет то,
до которого дочитал. Инцидент каталога: свод на 1245 строк, две строки об одном
предмете — где живёт состояние находки, — расходящиеся по двум осям сразу.

## Почему это перепись, а не поиск

Наивный поиск по словам «только» и «единственный» даёт в `CLAUDE.md`
тринадцать совпадений, из которых исключительных **восемь**. Остальные пять —
обычные ограничительные обороты: «перенесено только то, что вытекает из среды»,
«отличается только счётом за машинное время», «допускает в имени только ASCII».
Гейт, краснеющий на них, — ровно тот, который приучаются пропускать (051).

Поэтому правило 182 применено буквально: требование разложено надвое.

**Суждением решается** — «это исключительное утверждение или обычное
ограничение?». Гейт этого не подменяет и не притворяется, что может.

**Данными решается** — всё остальное, и его держит машина:

1. **Предмет занят.** Два утверждения об одном предмете — отказ, и это ровно
   тот случай, ради которого правило написано. Видно в момент внесения второго,
   а не при чтении документа сверху вниз.
2. **Утверждение живо.** Текст переписи обязан дословно находиться в названном
   документе. Переформулировали абзац — перепись отстала, и отстала бы молча:
   утверждение осталось бы объявленным, а в документе его бы не было.
3. **Документ существует.** Адрес, разрешимый по форме и мёртвый по сути,
   переживает переименование без единого сигнала.

## Чего гейт не ловит, и это сказано здесь

**Незаписанное утверждение.** Автор, дописавший в свод второе исключительное
утверждение и не внёсший его в перепись, гейтом не пойман — пойман приёмкой.
Перепись сужает щель до одного действия, но не закрывает её.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from utf8_output import force_utf8_output

EXIT_FAILED = 1
EXIT_BROKEN = 2

#: Перепись. Имя и место наши: контракт каталога такого файла не требует.
ПЕРЕПИСЬ = Path(".rules") / "exclusive.json"

#: Версия формата переписи — не выгрузки каталога и не ответа ему. Три разных
#: числа уже звались одним ключом `schema` (правило 164).
СХЕМА = "1.0"


@dataclass(frozen=True)
class Итог:
    """Находки и **счёт**: утверждений в переписи, документов под ними."""

    находки: list[str]
    утверждений: int
    документов: int
    переписи_нет: bool = False
    """Файла переписи в дереве нет вовсе — сверять нечего.

    Отличается от пустой переписи, и это не педантизм (039). Пустая отвечает
    «исключительных утверждений в проекте нет» — утверждение о
    действительности, и оно бывает ложным. Отсутствие файла означает «этот
    проект переписи не ведёт», и краснеть на нём значило бы требовать её от
    любого дерева, включая подделочные в наборе тестов.

    Тихого разоружения это не даёт: адрес `.rules/exclusive.json` назван в
    ответе каталогу (правило 181), а `scripts/rules_answer.py` отвергает
    ответ с адресом, которого в дереве нет. Файл, удалённый молча, красит
    соседний гейт.
    """


def проверить(корень: Path) -> Итог:
    """Сверить перепись с деревом.

    Находка здесь — **отказ**: каждая решается однозначно, без догадок о
    намерении автора.
    """
    файл = корень / ПЕРЕПИСЬ
    if not файл.is_file():
        return Итог([], 0, 0, переписи_нет=True)
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError) as отказ:
        return Итог([f"{ПЕРЕПИСЬ}: перепись не прочитана — {отказ}"], 0, 0)

    схема = данные.get("schema")
    if схема != СХЕМА:
        return Итог(
            [
                f"{ПЕРЕПИСЬ}: версия формата {схема!r}, а этот гейт читает "
                f"{СХЕМА!r}. Подъём версии — повод перечитать перепись, а не "
                "разобрать её как получится"
            ],
            0,
            0,
        )

    утверждения = данные.get("claims")
    if not isinstance(утверждения, list) or not утверждения:
        return Итог(
            [
                f"{ПЕРЕПИСЬ}: не названо ни одного утверждения. Пустая перепись "
                "отвечает «исключительных утверждений в проекте нет», а это "
                "утверждение о действительности, а не пропуск"
            ],
            0,
            0,
        )

    находки: list[str] = []
    предметы: dict[str, str] = {}
    документы: set[str] = set()
    тексты: dict[str, str] = {}

    for номер, запись in enumerate(утверждения, 1):
        if not isinstance(запись, dict):
            находки.append(f"утверждение №{номер}: запись не объект")
            continue

        предмет = str(запись.get("subject", "")).strip()
        документ = str(запись.get("document", "")).strip()
        текст = str(запись.get("claim", "")).strip()

        if not предмет or not документ or not текст:
            находки.append(
                f"утверждение №{номер}: нужны все три поля — subject, document, "
                "claim. Утверждение без предмета не с чем сверить, а именно "
                "предмет и делает второе утверждение нарушением"
            )
            continue

        прежний = предметы.get(предмет)
        if прежний is not None:
            находки.append(
                f"предмет «{предмет}» занят: о нём уже сказано исключительно в "
                f"{прежний}. Два таких утверждения друг друга не уточняют — "
                "каждое запрещает второе, и оба перестают действовать"
            )
            continue
        предметы[предмет] = документ
        документы.add(документ)

        if документ not in тексты:
            путь = корень / документ
            if not путь.is_file():
                находки.append(
                    f"{предмет}: документа {документ} в дереве нет. Адрес, "
                    "разрешимый по форме и мёртвый по сути, переживает "
                    "переименование без единого сигнала"
                )
                continue
            тексты[документ] = путь.read_text(encoding="utf-8")

        if текст not in тексты[документ]:
            находки.append(
                f"{предмет}: в {документ} этого текста больше нет. Перепись "
                "отстала от документа — утверждение объявлено, а исполнять "
                "нечего, и обнаружилось бы это только при споре"
            )

    return Итог(находки, len(предметы), len(документы))


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    аргументы = list(sys.argv[1:] if argv is None else argv)
    корень = Path(аргументы[0]) if аргументы else Path(__file__).resolve().parent.parent

    try:
        итог = проверить(корень)
    except OSError as отказ:
        print(f"не отработал: перепись не прочитана — {отказ}", file=sys.stderr)
        return EXIT_BROKEN

    if итог.переписи_нет:
        print(f"{ПЕРЕПИСЬ}: переписи нет — сверять нечего")
        return 0

    for находка in итог.находки:
        print(находка, file=sys.stderr)
    print(
        f"исключительных утверждений {итог.утверждений} в документах {итог.документов}"
    )
    return EXIT_FAILED if итог.находки else 0


if __name__ == "__main__":
    raise SystemExit(main())
