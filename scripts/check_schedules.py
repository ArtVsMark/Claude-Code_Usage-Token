"""Цена прогона по расписанию объявляется числом, а гейт её СЧИТАЕТ (правило 033).

Расписание тратит квоту площадки **фоном**: прогон, ходящий 48 раз в сутки,
выжигает лимит не рывком, а ровным потоком, и обнаруживается это отказом
СОСЕДНЕГО прогона, а не своего. `CLAUDE.md` § «Работа с GitHub» уже называет
цену одной GraphQL-операции — 300 из 5000 против 1 у REST; эта проверка — та же
арифметика, только для расписаний.

## Что здесь машинное, а что нет

Правило 182 применено буквально.

**Суждением решается** — сколько вызовов наружу делает прогон в худшем случае.
Это свойство кода, а не расписания, и посчитать его разбором нельзя: ветвления,
циклы по открытым изменениям, повторы при отказах. Число **объявляет автор**, и
рядом с ним пишет, из чего оно получено, — поле `why`.

**Данными решается** — всё остальное, и его считает машина:

1. **Худший час.** Из cron выводится, сколько раз прогон стартует в каждый час
   суток; произведение на объявленную цену суммируется по всем расписаниям
   этого часа, и берётся максимум. Умножать в уме — ровно та операция, которую
   не делают.
2. **Бюджет.** Худший час обязан уложиться в объявленную долю часового лимита.
3. **Полнота переписи.** Прогон с `schedule:` обязан быть здесь. Незаявленный
   прогон — самая дешёвая ошибка: расписание добавляют строкой, а цену не
   называет никто.

## Чего гейт не ловит

**Неверно объявленное число.** Автор, написавший 5 вместо 50, гейтом не пойман.
Перепись переносит ошибку из «никто не считал» в «названо и посчитано неверно»
— это разные ошибки, и вторая хотя бы видна.
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from utf8_output import force_utf8_output

EXIT_FAILED = 1
EXIT_BROKEN = 2

#: Перепись цены. Имя и место наши: контракт каталога такого файла не требует.
ПЕРЕПИСЬ = Path(".rules") / "schedules.json"

#: Версия формата переписи — не выгрузки каталога и не ответа ему (164).
СХЕМА = "1.0"

WORKFLOWS = Path(".github") / "workflows"

_РАСПИСАНИЕ = re.compile(r"^\s*schedule:\s*$", re.MULTILINE)


@dataclass(frozen=True)
class Итог:
    """Находки и **счёт**: расписаний, худший час, бюджет."""

    находки: list[str]
    расписаний: int
    худший_час: int
    бюджет: int
    переписи_нет: bool = False
    """Переписи в дереве нет вовсе — считать нечего.

    Отличается от пустой переписи (039). Пустая при живых расписаниях отвечает
    «цены у них нет», и это ложь; отсутствие файла означает «этот проект цену
    расписаний не ведёт». Тихого разоружения не даёт: адрес переписи назван в
    ответе каталогу по правилу 033, а `scripts/rules_answer.py` отвергает
    адрес, которого в дереве нет.
    """


def _поле(значение: str, предел: int) -> set[int] | None:
    """Значения одного поля cron: ``*``, список, диапазон, шаг. ``None`` — не разобрано.

    Отказ, а не догадка: непонятое поле дало бы заниженное число стартов, то
    есть заниженную цену — ошибку в ту самую сторону, ради которой гейт заведён.
    """
    итог: set[int] = set()
    for кусок in значение.split(","):
        шаг = 1
        if "/" in кусок:
            кусок, _, хвост = кусок.partition("/")
            if not хвост.isdigit() or int(хвост) < 1:
                return None
            шаг = int(хвост)
        if кусок == "*":
            начало, конец = 0, предел
        elif "-" in кусок.lstrip("-"):
            левое, _, правое = кусок.partition("-")
            if not (левое.isdigit() and правое.isdigit()):
                return None
            начало, конец = int(левое), int(правое)
        elif кусок.isdigit():
            начало = конец = int(кусок)
        else:
            return None
        if начало > конец or конец > предел:
            return None
        итог.update(range(начало, конец + 1, шаг))
    return итог or None


def стартов_по_часам(cron: str) -> dict[int, int] | None:
    """Сколько раз расписание стартует в каждый час суток. ``None`` — не разобрано.

    Дни недели и месяца не учитываются намеренно: считается **худший** час, а
    ограничение по дням его только снижает. Завышенная оценка здесь безопасна,
    заниженная — нет.
    """
    поля = cron.split()
    if len(поля) != 5:
        return None
    минуты = _поле(поля[0], 59)
    часы = _поле(поля[1], 23)
    if минуты is None or часы is None:
        return None
    return {час: len(минуты) for час in sorted(часы)}


def _расписания_в_дереве(корень: Path) -> set[str]:
    """Прогоны с блоком ``schedule:`` — то, что перепись обязана покрыть."""
    каталог = корень / WORKFLOWS
    if not каталог.is_dir():
        return set()
    return {
        (WORKFLOWS / файл.name).as_posix()
        for файл in sorted(каталог.iterdir())
        if файл.suffix in {".yml", ".yaml"}
        and _РАСПИСАНИЕ.search(файл.read_text(encoding="utf-8")) is not None
    }


def проверить(корень: Path) -> Итог:
    """Сверить перепись с деревом и посчитать худший час."""
    файл = корень / ПЕРЕПИСЬ
    if not файл.is_file():
        return Итог([], 0, 0, 0, переписи_нет=True)
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError) as отказ:
        return Итог([f"{ПЕРЕПИСЬ}: перепись не прочитана — {отказ}"], 0, 0, 0)

    if данные.get("schema") != СХЕМА:
        return Итог(
            [
                f"{ПЕРЕПИСЬ}: версия формата {данные.get('schema')!r}, а этот "
                f"гейт читает {СХЕМА!r}. Подъём — повод перечитать (157)"
            ],
            0,
            0,
            0,
        )

    предел = данные.get("hourly_limit")
    доля = данные.get("budget_share")
    if not isinstance(предел, int) or not isinstance(доля, int | float):
        return Итог(
            [
                f"{ПЕРЕПИСЬ}: не объявлены hourly_limit и budget_share — "
                "не с чем сверять"
            ],
            0,
            0,
            0,
        )
    бюджет = int(предел * доля)

    находки: list[str] = []
    по_часам: dict[int, int] = {}
    объявленные: set[str] = set()

    for номер, запись in enumerate(данные.get("schedules", []), 1):
        if not isinstance(запись, dict):
            находки.append(f"расписание №{номер}: запись не объект")
            continue
        прогон = str(запись.get("workflow", "")).strip()
        cron = str(запись.get("cron", "")).strip()
        цена = запись.get("calls_per_run")
        причина = str(запись.get("why", "")).strip()

        if not прогон or not cron or not isinstance(цена, int) or not причина:
            находки.append(
                f"расписание №{номер}: нужны workflow, cron, calls_per_run и why. "
                "Число без why — это не объявленная цена, а цифра"
            )
            continue

        объявленные.add(прогон)
        if not (корень / прогон).is_file():
            находки.append(f"{прогон}: такого прогона в дереве нет")
            continue

        старты = стартов_по_часам(cron)
        if старты is None:
            находки.append(
                f"{прогон}: расписание {cron!r} не разобрано. Непонятое поле "
                "дало бы ЗАНИЖЕННУЮ цену — ошибку в ту самую сторону, ради "
                "которой гейт заведён"
            )
            continue

        for час, разов in старты.items():
            по_часам[час] = по_часам.get(час, 0) + разов * цена

    for прогон in sorted(_расписания_в_дереве(корень) - объявленные):
        находки.append(
            f"{прогон}: прогон идёт по расписанию, а цена его не объявлена. "
            "Расписание добавляют строкой, и посчитать его не догадается никто"
        )

    худший = max(по_часам.values(), default=0)
    if худший > бюджет:
        час = max(по_часам, key=lambda ч: по_часам[ч])
        находки.append(
            f"худший час ({час}:00) просит {худший} вызовов при бюджете {бюджет} "
            f"({доля:.0%} от {предел} в час). Лимит выжигается фоном, и отказ "
            "приходит соседнему прогону, а не этому"
        )

    return Итог(находки, len(объявленные), худший, бюджет)


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    аргументы = list(sys.argv[1:] if argv is None else argv)
    корень = Path(аргументы[0]) if аргументы else Path(__file__).resolve().parent.parent

    try:
        итог = проверить(корень)
    except OSError as отказ:
        print(f"не отработал: {отказ}", file=sys.stderr)
        return EXIT_BROKEN

    if итог.переписи_нет:
        print(f"{ПЕРЕПИСЬ}: переписи нет — считать нечего")
        return 0

    for находка in итог.находки:
        print(находка, file=sys.stderr)
    print(
        f"расписаний {итог.расписаний}, худший час {итог.худший_час} "
        f"вызовов при бюджете {итог.бюджет}"
    )
    return EXIT_FAILED if итог.находки else 0


if __name__ == "__main__":
    raise SystemExit(main())
