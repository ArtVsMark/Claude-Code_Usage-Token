"""Адресат для красного по расписанию (#90).

Прогон по расписанию, упавший молча, отличается от незапущенного только счётом
за машинное время. Красное на вкладке прогонов адресатом не является: вкладку
открывают, когда чего-то ждут, а от расписания ждать нечего — оно работает
само.

## Замер, ради которого это написано

Прогонов по расписанию здесь два, и ни у одного отказ не доходил до человека.

**Очередь мержей** ходит `13,43 * * * *` — 48 раз в сутки. Пока она лежит, не
мержится ничего, и выглядит это как «проверки ещё идут».

**Входящие** ведут задачу-указатель, и она настоящий адресат — но только пока
прогон доходит до конца. Упал раньше — задача не изменилась, и молчание
неотличимо от «нового нет». Ровно такой сбой уже был (#78), и заметили его
потому, что смотрели в задачу, а не в вердикт.

## Одна задача на прогон, а не одна на всех

Состояние тогда — это **существование задачи**, и разбирать нечего. Общая
задача со списком красных потребовала бы читать собственное тело обратно, а
разбор своего же вывода ломается первой правкой формата.

## Почему повторный отказ не пишет комментарий

Очередь падает 48 раз в сутки; 48 комментариев — это не адресат, а способ
отписаться от задачи. Первый отказ **создаёт** задачу (уведомление уходит),
последующие **тихо обновляют тело**: правка тела подписчикам не рассылается.

## Что этот сторож не ловит

Прогон, умерший так, что событие о завершении не пришло вовсе — снятый
раннер, отменённая площадкой очередь. Такое молчание неотличимо от «не
запускалось», и различить его можно только опросом по времени, то есть ещё
одним прогоном по расписанию — у которого была бы та же беда.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence

import gh_rest
from utf8_output import force_utf8_output

#: Механизм не отработал: площадка отказала, задачу не завести.
EXIT_BROKEN = 2

#: Заголовок задачи-будильника. Он же ключ поиска: одна задача на прогон,
#: и её существование ЕСТЬ состояние.
ЗАГОЛОВОК = "Прогон по расписанию упал: {workflow}"

#: Исходы, при которых прогон считается упавшим. `cancelled` сюда НЕ входит:
#: отмену делает человек или concurrency, и будить по ней значит будить на
#: каждое собственное действие.
ПАДЕНИЯ = frozenset({"failure", "timed_out"})


def найти_задачу(repo: str, заголовок: str) -> int | None:
    """Номер открытой задачи с таким заголовком, либо ``None``.

    Список `/issues` отдаёт и pull request'ы — у них есть ключ
    ``pull_request``. Без отсева сторож однажды принял бы PR с совпавшим
    заголовком за свою задачу и стал бы править чужое.
    """
    for запись in gh_rest.paged(f"/repos/{repo}/issues", params={"state": "open"}):
        if not isinstance(запись, dict) or "pull_request" in запись:
            continue
        if запись.get("title") == заголовок:
            номер = запись.get("number")
            return int(номер) if isinstance(номер, int) else None
    return None


def тело(workflow: str, run_url: str) -> str:
    """Тело задачи. Одно и то же при заведении и при обновлении."""
    return (
        f"Прогон **{workflow}** завершился отказом.\n"
        f"\n"
        f"Последний упавший прогон: {run_url}\n"
        f"\n"
        f"Эта задача заводится один раз и закрывается сама, как только тот же "
        f"прогон снова зелёный. Повторные отказы её не комментируют — они "
        f"обновляют этот текст молча: прогон по расписанию падает десятками раз "
        f"в сутки, и комментарий на каждый был бы способом от задачи "
        f"отписаться, а не адресатом.\n"
        f"\n"
        f"Ведёт `scripts/schedule_alarm.py` (#90). Закрывать руками не нужно; "
        f"закрытая вручную задача заведётся заново при следующем отказе.\n"
    )


def поднять(repo: str, workflow: str, run_url: str) -> str:
    """Завести задачу или обновить существующую. Возвращает, что сделано."""
    заголовок = ЗАГОЛОВОК.format(workflow=workflow)
    номер = найти_задачу(repo, заголовок)
    if номер is None:
        ответ = gh_rest.request(
            "POST",
            f"/repos/{repo}/issues",
            body={"title": заголовок, "body": тело(workflow, run_url)},
        )
        новый = ответ.get("number") if isinstance(ответ, dict) else "?"
        return f"заведена задача #{новый}: {заголовок}"
    gh_rest.request(
        "PATCH",
        f"/repos/{repo}/issues/{номер}",
        body={"body": тело(workflow, run_url)},
    )
    return f"задача #{номер} уже открыта — тело обновлено молча, без комментария"


def снять(repo: str, workflow: str, run_url: str) -> str:
    """Закрыть задачу, если она открыта. Возвращает, что сделано."""
    заголовок = ЗАГОЛОВОК.format(workflow=workflow)
    номер = найти_задачу(repo, заголовок)
    if номер is None:
        return f"задачи по «{workflow}» нет — закрывать нечего"
    gh_rest.request(
        "POST",
        f"/repos/{repo}/issues/{номер}/comments",
        body={"body": f"Прогон снова зелёный: {run_url}"},
    )
    gh_rest.request(
        "PATCH",
        f"/repos/{repo}/issues/{номер}",
        body={"state": "closed", "state_reason": "completed"},
    )
    return f"задача #{номер} закрыта: прогон снова зелёный"


def build_parser() -> argparse.ArgumentParser:
    парсер = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    парсер.add_argument("--workflow", required=True, help="имя упавшего прогона")
    парсер.add_argument("--conclusion", required=True, help="исход прогона")
    парсер.add_argument("--run-url", default="", help="ссылка на прогон")
    парсер.add_argument("--repo", default="", help="владелец/репозиторий")
    return парсер


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    аргументы = build_parser().parse_args(list(argv) if argv is not None else None)

    if not gh_rest.token():
        # Не покраснеть: красное тут означало бы поломку механизма, а не
        # ненастроенное окружение. Но и промолчать нельзя — иначе сторож
        # неотличим от работающего.
        print(
            "::warning::токена нет — будильник не сработал. Задача об упавшем "
            "прогоне не заведена и не закрыта",
            file=sys.stderr,
        )
        return 0

    try:
        repo = аргументы.repo or gh_rest.repository()
        исход = аргументы.conclusion.strip().lower()
        if исход in ПАДЕНИЯ:
            print(поднять(repo, аргументы.workflow, аргументы.run_url))
        elif исход == "success":
            print(снять(repo, аргументы.workflow, аргументы.run_url))
        else:
            # Отмена, пропуск, «ожидает действия» — не отказ и не успех.
            # Печатаем вслух: «ничего не сделал» и «не запускался» обязаны
            # различаться, иначе отмена читается как бездействие.
            print(f"исход «{исход}» — не отказ и не успех, будильник не трогаем")
    except gh_rest.GitHubError as отказ:
        print(f"::error::будильник не отработал: {отказ}", file=sys.stderr)
        return EXIT_BROKEN
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
