"""Перепись адресов: ссылка называет репозиторий его нынешним именем.

## Почему нужна перепись, а не отказ

Правило 094 каталога говорит: переходная заглушка делает миграцию вечной,
поэтому ломать надо сразу и заметно. Здесь **ломать нечем**. Переименование
репозитория на GitHub оставляет редирект, отключить его нельзя, и старое имя
продолжает работать всюду: ссылка открывается, `raw.githubusercontent.com`
отдаёт файл, `uses:` тянет действие. Сигнала о незавершённой миграции не будет
ни одного.

Замер 2026-09-02, когда владелец переименовал три репозитория разом: двадцать
ссылок в четырнадцати файлах устарели, и **все восемь гейтов остались
зелёными**, а прогон `rules-inbox` по старому имени — успешным. Расхождение
нашла не проверка, а человек, назвавший его вслух.

Цена отложенного не «битая ссылка». Редирект держится, пока старое имя
свободно; как только его займёт кто угодно другой, `uses:` начнёт тянуть чужое
действие — а `rules-inbox.yml` выдаёт ему `issues: write`. Это уже исполнение
чужого кода под своим токеном.

## Как устроено

Все адреса своего владельца перечислены **белым списком** (правило 068) — и
свой собственный тоже. Переименование вносится в него **одной строкой**, после
чего гейт показывает пофайлово всё, что осталось со старым именем. Это и есть
перепись: одно место правится руками, остальное находится механизмом.

## Почему своё имя не берётся из `git remote`

Первая редакция брала его оттуда — как «живой источник» по правилу 049. Это
оказалось неверным, и выяснилось на первом же прогоне: **`git remote` тоже
устаревает**. Клон, сделанный до переименования, хранит старый адрес, git его
не обновляет, а работать он продолжает — по тому же редиректу. То есть источник,
взятый за живой, был ровно таким же устаревшим указателем, как проверяемые
ссылки, и гейт уверенно сообщил бы обратное тому, что есть.

Живой источник здесь один и только в прогоне: `GITHUB_REPOSITORY` заполняет
площадка. Поэтому в Actions гейт дополнительно сверяет с ним белый список — и
краснеет, если репозиторий переименовали, а список не поправили. Локально
такой сверки нет: сверять не с чем, и выдумывать замену значило бы вернуть ту
же ошибку.

## Границы

**Проверяется только свой владелец.** `actions/checkout@v4` и прочие чужие
адреса не трогаются: их состав — это инвентарь зависимостей, отдельная задача,
и белый список из них превратился бы в список, который никто не ведёт.

**Существование не проверяется.** Гейт работает без сети и отвечает на вопрос
«названо ли имя из списка», а не «жив ли адрес».
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from utf8_output import force_utf8_output

EXIT_FAILED = 1
EXIT_BROKEN = 2

#: Все адреса своего владельца, включая свой собственный. Единственное место,
#: куда переименование вносится руками; всё остальное находит гейт.
АДРЕСА = frozenset(
    {
        "ArtVsMark/Claude-Code_Usage-Token",
        "ArtVsMark/Engineering-Incidents-Playbook",
        "ArtVsMark/Claude-Code_Usage-Data",
        "ArtVsMark/Stepik-Python-Grader",
    }
)

#: Ссылка в прозе и в значке. `%2F` — то же самое после кодирования: значок
#: витрины подставляет адрес в параметр `url=`, и там косые заэкранированы.
_ССЫЛКА = re.compile(
    r"(?:github\.com|raw\.githubusercontent\.com)(?:/|%2[Ff])"
    r"([\w.-]+)(?:/|%2[Ff])([\w.-]+)"
)

#: Действие в workflow. Синтаксис `uses:` — не URL, и первым выражением он не
#: ловится, а ставка на нём выше всех остальных: это исполняемый чужой код.
_ДЕЙСТВИЕ = re.compile(r"^\s*-?\s*uses:\s*([\w.-]+)/([\w.-]+)@")


@dataclass(frozen=True)
class Находка:
    """Место, где записано имя, которого у нас больше нет."""

    path: str
    line: int
    адрес: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.адрес}"


def адрес_из_прогона() -> str:
    """Нынешнее имя репозитория, если его называет площадка. Иначе пусто.

    Единственный источник, который переименование переживает: `git remote`
    остаётся со старым адресом и продолжает работать по редиректу.
    """
    return os.environ.get("GITHUB_REPOSITORY", "").strip()


def список_свежий(адреса: frozenset[str], *, из_прогона: str) -> str | None:
    """Назван ли в списке тот репозиторий, в котором идёт прогон.

    Возвращает текст отказа или `None`. Вне прогона сверять не с чем, и это
    не отказ: локально живого источника имени попросту нет.
    """
    if not из_прогона:
        return None
    if из_прогона.lower() in {имя.lower() for имя in адреса}:
        return None
    return (
        f"площадка называет репозиторий {из_прогона}, а в списке АДРЕСА его нет. "
        "Похоже, репозиторий переименовали: впишите новое имя в "
        "scripts/repo_links.py — остальное гейт найдёт сам."
    )


def tracked_files(root: Path) -> list[Path]:
    """Файлы под версией. `-z` обязателен: без него git экранирует кириллицу.

    Ровно этот дефект уже выключал проверку на секреты (#24) — она печатала
    «всё чисто», не прочитав ни одного файла с русским именем.
    """
    ответ = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
        timeout=30,
    )
    return [root / имя for имя in ответ.stdout.split("\0") if имя]


def check_text(text: str, path: str, *, адреса: frozenset[str]) -> list[Находка]:
    """Найти адреса своего владельца, которых нет в списке."""
    разрешённые = {имя.lower() for имя in адреса}
    владельцы = {имя.split("/", 1)[0].lower() for имя in адреса}
    находки: list[Находка] = []
    for номер, строка in enumerate(text.splitlines(), start=1):
        пары = [(м.group(1), м.group(2)) for м in _ССЫЛКА.finditer(строка)]
        совпадение = _ДЕЙСТВИЕ.match(строка)
        if совпадение:
            пары.append((совпадение.group(1), совпадение.group(2)))
        for кто, что in пары:
            if кто.lower() not in владельцы:
                continue
            адрес = f"{кто}/{что}"
            if адрес.lower() not in разрешённые:
                находки.append(Находка(path, номер, адрес))
    return находки


def check_tree(
    root: Path,
    *,
    files: Sequence[Path] | None = None,
    адреса: frozenset[str] = АДРЕСА,
) -> list[Находка]:
    """Пройти дерево целиком.

    `files` даёт вызывающий, когда перечисление у него уже есть: в `preflight`
    оно одно на все проверки, и второй поход в git разошёлся бы с первым — как
    минимум в разборе не-ASCII имён, где эта разница уже стоила слепого гейта.
    """
    находки: list[Находка] = []
    for файл in tracked_files(root) if files is None else files:
        try:
            текст = файл.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            # Двоичное или нечитаемое — ссылок в нём не бывает.
            continue
        путь = файл.relative_to(root).as_posix()
        находки.extend(check_text(текст, путь, адреса=адреса))
    return находки


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    import argparse

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".", help="корень дерева")
    аргументы = parser.parse_args(argv)
    root = Path(аргументы.root).resolve()

    отказ = список_свежий(АДРЕСА, из_прогона=адрес_из_прогона())
    if отказ:
        print(отказ, file=sys.stderr)
        return EXIT_FAILED

    try:
        находки = check_tree(root)
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        print(f"перепись не отработала: {exc}", file=sys.stderr)
        return EXIT_BROKEN

    if находки:
        print(f"адресов не из списка: {len(находки)}")
        for находка in находки:
            print(f"  {находка}")
        print(
            "\nЛибо это старое имя после переименования — тогда правится ссылка, "
            "либо новый смежный репозиторий — тогда он вносится в АДРЕСА "
            "в scripts/repo_links.py."
        )
        return EXIT_FAILED

    print(f"перепись ссылок: адресов в списке {len(АДРЕСА)}, имён вне списка нет")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
