"""У растущей части документа есть предел, выраженный числом (правило 108).

Документ, растущий без предела, перестают читать целиком: актуальную часть
ищут прокруткой, а старую не выносят, потому что никто не сказал, когда пора.
Инцидент каталога — свод на 1245 строк с ДВУМЯ указаниями об одном предмете,
противоречащими друг другу: второе дописали, не найдя первого.

## Предел объявляется числом, а вышедшее за него называется поимённо

Не «слишком длинно», а «504 из 600»: число видно в каждом прогоне, и до отказа
его рост заметен. Что делать при переполнении, сказано рядом с пределом — иначе
отказ сообщает о проблеме и молчит о выходе.

## Чего гейт не проверяет

**Дословность переноса в архив.** Что вынесенное уехало целиком, а не пересказом,
машине не видно, и это здесь названо, а не обнаружится потом.
"""

from __future__ import annotations

import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from utf8_output import force_utf8_output

EXIT_FAILED = 1
EXIT_BROKEN = 2


@dataclass(frozen=True)
class Предел:
    """Документ, его мера, число и что делать при переполнении."""

    путь: str
    мера: str
    предел: int
    выход: str


#: Пределы растущих документов. Список в коде, а не в переписи: документов
#: четыре, каждый назван с причиной, и второй файл рядом с этим списком был бы
#: третьей классификацией той же территории.
#:
#: Числа выбраны с запасом от нынешнего размера, а не впритык: предел, который
#: краснеет назавтра, приучают обходить, а не соблюдать (051).
ПРЕДЕЛЫ: tuple[Предел, ...] = (
    Предел(
        "CLAUDE.md",
        "строк",
        600,
        "вынести раздел в docs/ и оставить здесь ссылку. Свод читают целиком "
        "при старте каждого окна — его длина это цена КАЖДОГО окна, а не одного",
    ),
    Предел(
        "CHANGELOG.md",
        "разделов версий",
        3,
        "старшие разделы переносятся дословно в docs/archive/changelog-archive.md",
    ),
    Предел(
        "HISTORY.md",
        "строк",
        200,
        "вышедшее за окно переносится в docs/archive/history-archive.md",
    ),
    Предел(
        "docs/spec.md",
        "строк",
        400,
        "раздел, выросший в самостоятельный предмет, выносится в свой документ",
    ),
)

_ВЕРСИЯ = re.compile(r"^## ", re.MULTILINE)


@dataclass(frozen=True)
class Итог:
    находки: list[str]
    проверено: int
    самый_полный: str


def _мера(предел: Предел, текст: str) -> int:
    if предел.мера == "строк":
        return len(текст.splitlines())
    return len(_ВЕРСИЯ.findall(текст))


def проверить(корень: Path) -> Итог:
    находки: list[str] = []
    проверено = 0
    полнота = 0.0
    самый = "—"

    for предел in ПРЕДЕЛЫ:
        путь = корень / предел.путь
        if not путь.is_file():
            # Документа нет — предел не о чем. Отказ здесь требовал бы файла от
            # любого дерева, включая подделочные в наборе тестов.
            continue
        проверено += 1
        сколько = _мера(предел, путь.read_text(encoding="utf-8"))
        доля = сколько / предел.предел
        if доля > полнота:
            полнота, самый = доля, f"{предел.путь} {сколько}/{предел.предел}"
        if сколько > предел.предел:
            находки.append(
                f"{предел.путь}: {сколько} {предел.мера} при пределе "
                f"{предел.предел}. Что делать: {предел.выход}"
            )

    return Итог(находки, проверено, самый)


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    аргументы = list(sys.argv[1:] if argv is None else argv)
    корень = Path(аргументы[0]) if аргументы else Path(__file__).resolve().parent.parent

    try:
        итог = проверить(корень)
    except OSError as отказ:
        print(f"не отработал: {отказ}", file=sys.stderr)
        return EXIT_BROKEN

    for находка in итог.находки:
        print(находка, file=sys.stderr)
    print(f"растущих документов {итог.проверено}, полнее всего {итог.самый_полный}")
    return EXIT_FAILED if итог.находки else 0


if __name__ == "__main__":
    raise SystemExit(main())
