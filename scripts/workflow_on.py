"""События прогона: что объявлено в блоке `on:` — одним разбором на дерево.

## Почему один разбор (правило 214, #141)

Вопрос «на каких событиях идёт прогон» задавали четыре места, и каждое
отвечало своим разбором: обязательная проверка (`pr_check`), гейт групп отмены
(`concurrency_head`), перепись расписаний (`check_schedules`) и тест сторожа
расписаний. Ответы уже расходились: однострочную форму `on: [pull_request]`
одни разбирали как список, другие — поиском подстроки, а `schedule:` перепись
находила на любом отступе, в том числе вне `on:`.

Предмет здесь — **набор событий**, а не вопрос к нему. Какие события считать
своими, решает вызывающий: обязательной проверке нужен ровно `pull_request`
(она ищет прогоны с этим событием), а гейту отмены — и `pull_request_target`,
потому что гонка групп у него та же.

## Какие формы разбираются

Три законные формы ключа `on` (голый, в двойных и в одинарных кавычках —
YAML 1.1 читает голое `on` как булево) и три формы значения: скаляр
(`on: push`), поток-список (`on: [push, pull_request]`) и блок — ключами
(`  push:`) или списком (`  - push`). Событием в блоке считается только строка
**первого** отступа: `branches:` под `push:` — не событие.

Чего нет: потока-отображения (`on: {push: …}`) и якорей YAML. Полного разбора
YAML здесь нет намеренно — гейты обходятся стандартной библиотекой, а
зависимость сделала бы обязательную проверку заложницей сборки.
"""

import re

#: Строка ключа `on` верхнего уровня; группа — всё после двоеточия.
_КЛЮЧ_ON = re.compile(r"""^(?:on|"on"|'on')\s*:(.*)$""")

#: Имя события в строке блока: ключом (`  push:`) или элементом (`  - push`).
_СОБЫТИЕ = re.compile(r"^\s*-?\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?::|$)")


def _без_комментария(строка: str) -> str:
    return строка.split("#", 1)[0].rstrip()


def события(текст: str) -> frozenset[str]:
    """Имена событий из блока `on:` прогона; пустой набор, если блока нет."""
    строки = текст.splitlines()
    for номер, строка in enumerate(строки):
        совпадение = _КЛЮЧ_ON.match(строка)
        if совпадение is None:
            continue
        хвост = _без_комментария(совпадение.group(1)).strip()
        if хвост:
            return frozenset(слово for слово in re.split(r"[\s,\[\]]+", хвост) if слово)
        return _блок(строки[номер + 1 :])
    return frozenset()


def _блок(строки: list[str]) -> frozenset[str]:
    """События из строк под `on:` — до первой строки без отступа."""
    найдено: set[str] = set()
    отступ: int | None = None
    for сырая in строки:
        строка = _без_комментария(сырая)
        if not строка.strip():
            continue
        if not строка.startswith((" ", "\t")):
            break
        свой = len(строка) - len(строка.lstrip())
        if отступ is None:
            отступ = свой
        if свой != отступ:
            continue
        совпадение = _СОБЫТИЕ.match(строка)
        if совпадение is not None:
            найдено.add(совпадение.group(1))
    return frozenset(найдено)
