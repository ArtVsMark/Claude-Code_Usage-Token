"""Один участник — одна подпись в КОНЕЧНОЙ истории (правило 123 каталога, #94).

Проверяется история общей ветки, а не коммит ветки изменения, и это главное в
устройстве. Строку соавторства, которую пишет окно, площадка при слиянии
**пересобирает**: свой трейлер она ставит всегда и имя берёт из аккаунта по
адресу, а не из написанного. Значит утверждение «подпись одна» верно или неверно
только про то, что уехало, — проверять коммит ветки бессмысленно.

## Замер, из-за которого это заведено

Перебор всей истории `main` 2026-09-03, 57 коммитов: подпись ОДНОГО участника в
двух видах — 52 раза «Co-authored-by: Claude» и 33 раза «Co-Authored-By: Claude
Opus 5». Разбор по способу слияния объяснил закономерность полностью:

| PR содержал | сколько | подпись окна выжила |
|---|---|---|
| один коммит | 40 | 0 |
| несколько коммитов | 14 | 14 |

Один коммит — его тело становится телом итогового, трейлеры нормализуются, и
строка окна схлопывается с площадкиной. Несколько — тела вставляются как ТЕКСТ,
строка окна оказывается в середине и трейлером уже не считается.

Починено в `scripts/merge_queue.py`: очередь собирает тело squash сама и
снимает из него подпись окна, оставляя площадкину единственной.

## Почему у гейта объявленное начало

Прошлое не переписывается: 33 коммита с двойной подписью уже в истории, и
краснеть на них вечно значило бы приучать пропускать красное (051). Поэтому
проверяется история ПОСЛЕ объявленного коммита — приём взят у соседа, который
держит то же правило так же.
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from utf8_output import force_utf8_output

EXIT_FAILED = 1
EXIT_BROKEN = 2

#: С какого коммита `main` история обязана нести одну подпись на участника.
#:
#: ПРАВКА СБОРЩИКА СООБЩЕНИЙ НЕ ДЕЙСТВУЕТ НА СВОЙ СОБСТВЕННЫЙ МЕРЖ, и это не
#: случайность, а устройство: тело squash собирает очередь, работающая с
#: ПРЕЖНЕЙ головы общей ветки. Её первый предмет — всегда СЛЕДУЮЩИЙ мерж.
#:
#: Поэтому начало ставится на мерж самой правки (32fdc68), а не перед ним:
#: предыдущая редакция поставила его на 20a287f, «за границу ущерба», и тут же
#: покрасила общую ветку — мерж #111 собирала ещё старая очередь и подписи не
#: поставила. Ошибка того же рода, что и породившая правку: вывод о поведении
#: механизма сделан без учёта того, КАКАЯ его версия работала.
#:
#: Начало двигалось ОДИН раз, и это записано, а не затёрто.
#:
#: Первое было 328377c — голова на момент первой починки. За ней уехали четыре
#: мержа, и три из них БЕЗ подписи вовсе: очередь стала передавать площадке
#: готовое `commit_message`, а площадка дописывает свой трейлер, только когда
#: собирает тело сама. Замер #94 снят на прежнем её поведении и после правки
#: описывать мир перестал.
#:
#: Прошлое не переписывается — ни двойные подписи до 328377c, ни пустые после
#: (их четыре: #108, #109, #110 и мерж самой правки #111).
НАЧАЛО = "32fdc68a24aa0d6facda97d81c7f9dd777fd0513"

#: Ветка, чья история и есть предмет: подпись собирается при слиянии в неё.
ВЕТКА = "main"

#: Локальный git отвечает мгновенно; дедлайн назван, потому что без него вызов
#: без сети может ждать ввода с терминала и висеть до упора (CLAUDE.md).
LOCAL_TIMEOUT = 30

_ТРЕЙЛЕР = re.compile(r"(?im)^[ \t]*co-authored-by:[ \t]*(?P<имя>[^<]+?)[ \t]*<")


@dataclass(frozen=True)
class Итог:
    """Находки и **счёт**: коммитов просмотрено, имён найдено."""

    находки: list[str]
    коммитов: int
    имена: list[str]
    истории_нет: bool = False
    """История недоступна — мелкий клон или начало неизвестно.

    Отличается от «имён больше одного» (039). Прогоны берут дерево с
    `fetch-depth: 1`, и `git log` там пуст не потому, что подписи в порядке.
    Молчаливый ноль читался бы как «проверено и чисто» — то есть гейт отвечал
    бы зелёным, ничего не проверив.
    """


def _git(корень: Path, *аргументы: str) -> tuple[int, str]:
    итог = subprocess.run(
        ("git", *аргументы),
        cwd=корень,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=LOCAL_TIMEOUT,
        env={"GIT_TERMINAL_PROMPT": "0", "PATH": "/usr/bin:/bin:/usr/local/bin"},
    )
    return итог.returncode, итог.stdout


def _голова(корень: Path, ветка: str) -> str | None:
    """Ссылка на общую ветку: сперва следящая за удалённой, потом локальная.

    Порядок не косметический. Локальная `main` в рабочем дереве окна может
    отставать на десяток мержей — окно на ней не сидит и её не обновляет, — и
    `начало..main` тогда пусто НЕ потому, что подписи в порядке.

    Замер 2026-09-07: локальная `main` отставала, гейт напечатал «коммитов 0,
    имён 0» и прошёл, пока в общей ветке лежали четыре мержа, три из которых
    были БЕЗ подписи вовсе. Ложное зелено на устаревшей ссылке — ровно тот
    способ соврать, ради которого гейт и заведён.
    """
    for имя in (f"origin/{ветка}", ветка):
        код, _ = _git(корень, "rev-parse", "--verify", f"{имя}^{{commit}}")
        if код == 0:
            return имя
    return None


def проверить(корень: Path, *, начало: str = НАЧАЛО, ветка: str = ВЕТКА) -> Итог:
    """Сверить подписи в истории `ветка` после коммита `начало`."""
    код, _ = _git(корень, "cat-file", "-e", f"{начало}^{{commit}}")
    if код != 0:
        return Итог([], 0, [], истории_нет=True)

    голова = _голова(корень, ветка)
    if голова is None:
        return Итог([], 0, [], истории_нет=True)

    # НАЧАЛО обязано быть предком головы. Иначе измеряется не та история: пусто
    # здесь означает «ссылка не та», а не «после начала ничего не мержилось».
    код, _ = _git(корень, "merge-base", "--is-ancestor", начало, голова)
    if код != 0:
        return Итог([], 0, [], истории_нет=True)

    код, вывод = _git(
        корень, "log", "--first-parent", "--format=%B%x00", f"{начало}..{голова}"
    )
    if код != 0:
        return Итог([], 0, [], истории_нет=True)

    тела = [т for т in вывод.split("\0") if т.strip()]
    имена: dict[str, list[str]] = {}
    безымянные: list[str] = []
    for тело in тела:
        заголовок = тело.strip().splitlines()[0][:60]
        найдено = list(_ТРЕЙЛЕР.finditer(тело))
        if not найдено:
            безымянные.append(заголовок)
        for совпало in найдено:
            имя = совпало.group("имя").strip()
            имена.setdefault(имя, []).append(заголовок)

    находки: list[str] = []
    if безымянные:
        # НОЛЬ ПОДПИСЕЙ — ЭТО НЕ ОДНА, и прежняя редакция этого не ловила:
        # находкой считалось только «имён больше одного». Щель уехала в общую
        # ветку тремя коммитами подряд.
        перечень = "; ".join(f"«{з}»" for з in безымянные[:3])
        находки.append(
            f"коммитов без подписи участника: {len(безымянные)} — {перечень}. "
            "Ноль подписей это не одна: работу вело окно, а история об этом "
            "молчит. Подпись собирает очередь (scripts/merge_queue.py, ПОДПИСЬ); "
            "если её нет, значит собирает не она"
        )
    if len(имена) > 1:
        разбор = "; ".join(
            f"«{имя}» — {len(где)} раз, напр. «{где[0]}»"
            for имя, где in sorted(имена.items())
        )
        находки.append(
            f"один участник в истории под {len(имена)} именами: {разбор}. "
            "Строку, которую пишет окно, площадка при слиянии пересобирает — "
            "значит маршрут мержа изменился, и подпись снова двоится"
        )

    return Итог(находки, len(тела), sorted(имена))


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    аргументы = list(sys.argv[1:] if argv is None else argv)
    корень = Path(аргументы[0]) if аргументы else Path(__file__).resolve().parent.parent

    try:
        итог = проверить(корень)
    except (OSError, subprocess.SubprocessError) as отказ:
        print(f"не отработал: история не прочитана — {отказ}", file=sys.stderr)
        return EXIT_BROKEN

    if итог.истории_нет:
        print(f"истории после {НАЧАЛО[:7]} не видно — сверять нечего")
        return 0

    for находка in итог.находки:
        print(находка, file=sys.stderr)
    print(f"коммитов после {НАЧАЛО[:7]}: {итог.коммитов}, имён: {len(итог.имена)}")
    return EXIT_FAILED if итог.находки else 0


if __name__ == "__main__":
    raise SystemExit(main())
