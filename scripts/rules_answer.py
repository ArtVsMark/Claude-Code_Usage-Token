"""Ответ каталогу правил обязан быть разрешимым, а не правдоподобным (#47).

Проект — потребитель каталога
[Engineering-Incidents-Playbook](https://github.com/ArtVsMark/Engineering-Incidents-Playbook),
и отвечает ему файлом `.rules/bindings.json`: по записи на правило — держится
оно здесь, отклонено, неприменимо или ещё не разобрано.

## Почему у ответа обязан быть свой гейт

Ответ **не проверяется никем**. У себя каталог отвергает негодную запись до
слияния, а у потребителя не может: файл чужой, и красное оттуда снять нечем.
Значит проверять обязан сам потребитель — иначе его ответ расходится с
действительностью молча, что и произошло.

Замер 2026-09-03, до этого гейта, на собственном ответе из 162 записей:

| что не так | сколько |
|---|---|
| `schema` объявлена `1.0`, контракт требует `1.1` | 1 |
| `mechanism: process-step` — значение, объявленное устаревшим | 5 |
| `active`, чей `where` не называет ни одного адреса | 7 |
| правил каталога без записи вовсе | 13 |

Последние тринадцать — самое неприятное: **десять из них родились здесь** и
были приняты каталогом как 165–172, 175, 176. То есть механизм построен, а
ответа о нём нет.

## Что проверяется, и почему именно это

**Адрес, а не проза.** Контракт требует у `where` разрешимый адрес: путь,
образец вида `.github/workflows/*.yml` или корневой документ по имени. Ловит
это не форму записи, а **ложный механизм**: гейт, чей адрес нельзя назвать,
обычно и не гейт. У каталога замер по собственному ответу дал семь таких, и все
семь оказались утверждениями обо всех скриптах сразу, которых не проверяет
ничто.

**Адрес существует в дереве.** Своя добавка, которой в контракте нет: адрес
может быть разрешимым по форме и мёртвым по сути — файл переименовали, гейт
переехал. Проверка дешёвая, без сети, и ловит ровно то, что переживает
переименование молча.

**Устаревшее значение `mechanism`.** `process-step` контракт называет
устаревшим. Оставленное, оно однажды перестанет читаться на той стороне, а
здесь будет выглядеть ответом.

## Чего гейт НЕ проверяет

**Полноту ответа.** Сколько правил в каталоге — знает каталог, и узнать это
локально нечем: гейт работает без сети. Пробелы приносит прогон `rules-inbox` в
issue, и это его работа, а не этого гейта.

**Правдивость прозы.** «Держится гейтом» — утверждение о смысле, а не о форме;
проверить его может только человек. Гейт отвечает на вопрос «назван ли адрес и
существует ли он», а не «делает ли названное то, что обещано».
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from utf8_output import force_utf8_output

EXIT_FAILED = 1
EXIT_BROKEN = 2

#: Файл ответа. Имя и место заданы контрактом каталога, а не нами.
ОТВЕТ = Path(".rules") / "bindings.json"

#: Версия ФОРМАТА ОТВЕТА — не выгрузки и не выпуска каталога. Три разных числа
#: звались одним ключом `schema`, и на этом уже спотыкались: правило 164
#: каталога родилось ровно из такой путаницы, причём наш файл был в числе
#: примеров.
#:
#: 1.1 → 1.7 (#139), перечитано по export/README.md каталога, таблица полей:
#: механизм `skill` и поле `skill` (1.4, вторая форма адреса — 1.7);
#: `holdable` вместо `document_reason` и даты `analysed`/`decided` (1.5);
#: слово `refused` (1.6). Новые поля контракт спрашивает у записей НОВЫХ И
#: ТРОНУТЫХ — задним числом не проставляются, иначе их начнут ставить формально
#: (146). Поэтому гейт проверяет их форму и связи там, где они есть, а пробел
#: «вердикта о машине нет» считает числом, а не отказом. Обязателен без
#: оговорок один `machine_half` у `active` + `none`: таких записей немного, и
#: они заполнены целиком тем же заходом.
СХЕМА_ОТВЕТА = "1.7"

#: Версия ВЫГРУЗКИ каталога — число ЧУЖОЕ, и в этом весь смысл (#85).
#:
#: Сверка версии `СХЕМА_ОТВЕТА` выше односторонняя по построению: обе её
#: стороны наши — поле нашего файла и константа этого же репозитория. Подъём
#: версии У ИЗДАТЕЛЯ она не заметит никогда, а текст её отказа при этом
#: утверждает нечто о чужой стороне. Дословный признак нарушения правила 157.
#:
#: Починить это целиком нечем: версия формата ОТВЕТА объявлена контрактом
#: прозой, в таблице полей, и машиночитаемого числа у неё нет. Но у второй
#: половины контракта — выгрузки правил — число есть, и вот его сверка
#: настоящая: слева наша константа, справа файл каталога. Поднялась — контракт
#: полагается перечитать, а не разобрать как получится.
#:
#: Проверяется НЕ здесь, а в прогоне `.github/workflows/rules-inbox.yml`: у
#: этого гейта сети нет намеренно, а выгрузка живёт у каталога.
#:
#: ПЕРЕЧИТАНО 2 октября, 1.4 → 1.7 (#122), по docs/VERSIONING.md каталога:
#:
#: - 1.5 — у следа (`trails`) вторая форма, документ: `{"repo","doc",
#:   "section"}`, поля `issue` у неё НЕТ;
#: - 1.6 — у записи `claim` (буква требования) и `applies` (граница);
#: - 1.7 — связи записей: `refines`, `mentions`, `refined_by`, `mentioned_by`.
#:
#: Все три — прибавления, смысл знакомых полей не сменился. Наш код из выгрузки
#: читает ОДНО поле — `schema`, здесь же; следы читает скрипт каталога, а он
#: закреплён тегом в прогоне и `issue` берёт через `.get`. Правок кода подъём не
#: потребовал. Перечитывать по `claim` наши ответы стоит — заголовок задаёт
#: направление, а не предмет (#454 каталога), — но это работа над ответами, а
#: не над чтением выгрузки, и ведётся она отдельно.
СХЕМА_ВЫГРУЗКИ = "1.7"

#: Допустимые статусы и механизмы. `process-step` в списке нет намеренно:
#: контракт объявил его устаревшим, и запись с ним — не ответ, а его вид.
СТАТУСЫ = frozenset({"active", "rejected", "not-applicable", "unreviewed"})
МЕХАНИЗМЫ = frozenset({"gate", "pipeline", "skill", "document", "none"})

#: Механизмы, которые не краснеют: у них контракт спрашивает `holdable` —
#: можно ли держать правило МАШИНОЙ.
НЕ_КРАСНЕЮТ = frozenset({"document", "skill", "none"})

#: Словарь `holdable` (1.5, `refused` — с 1.6). Закрытый: счётчику знаменатель
#: надо разделить, а прозу сложить нельзя.
ДЕРЖИМОСТЬ = frozenset({"no", "not-yet", "conditional", "refused"})

#: Дата сверки и решения — `ГГГГ-ММ-ДД`.
_ДАТА = re.compile(r"^\d{4}-\d{2}-\d{2}$")

#: Навык плагина каталога: `<плагин>:<имя>`, так же, как он зовётся (1.7).
_НАВЫК_ПЛАГИНА = re.compile(r"^[a-z0-9][a-z0-9-]*:[a-z0-9][a-z0-9-]*$")
УСТАРЕВШИЕ_МЕХАНИЗМЫ = frozenset({"process-step"})

#: Разрешимый адрес: путь к файлу с расширением, образец с `*` либо корневой
#: документ по имени. Проза рядом разрешена контрактом, вместо адреса — нет.
#:
#: Ведущая точка обязательна в наборе первого символа: без неё `.rules/…` и
#: `.github/…` совпадали БЕЗ неё, путь не разрешался, и гейт объявлял мёртвыми
#: четыре живых адреса. Нашлось первым же прогоном на собственном дереве.
_АДРЕС = re.compile(r"[\w.][\w./*-]*\.(?:py|ya?ml|json|md|toml|cfg|ini|txt)\b")


@dataclass(frozen=True)
class Находка:
    """Одна негодная запись ответа."""

    правило: str
    message: str

    def __str__(self) -> str:
        return f"{ОТВЕТ.as_posix()}: правило {self.правило}: {self.message}"


@dataclass(frozen=True)
class Результат:
    """Находки и **счёт**: сколько записей разобрано и сколько из них с адресом.

    Счёт — часть вывода, а не отладка: «ответ в порядке» без числа записей
    неотличимо от «файл пуст», а именно так выглядел бы ответ, потерявший
    содержимое при слиянии.
    """

    находки: list[Находка]
    записей: int
    с_адресом: int
    без_держимости: int = 0
    """Записей с механизмом, который не краснеет, но без вердикта `holdable`.

    Не отказ, а число: контракт спрашивает поле у новых и тронутых записей, и
    этот счёт — остаток перечитывания (#139), видимый каждому прогону.
    """
    раскладка: dict[str, int] | None = None
    """Чем держится каждое правило — счёт для `facts.json`, один на дерево.

    Ключи: `total`, `not_applicable`, `rejected`, `unreviewed`, а у
    действующих — имя механизма. Неразобранная запись (не объект, статус вне
    контракта) идёт в `invalid`: сумма обязана сходиться с `total`. ``None`` —
    ответа нет или он не прочитан.

    Прежде `scripts/facts.py` считал раскладку сам, и неразобранное
    `unreviewed` попадало у него в механизм — то есть в «ничем не держится»,
    тогда как этот гейт его туда не считает (правило 197, находка #151).
    """
    ничем: int = 0
    """Правил, признанных ДЕЙСТВУЮЩИМИ и не держащихся ничем.

    Число называется здесь, а не только в задаче-«входящих», потому что правило
    177 требует именно этого: незакрытая работа по правилам идёт впереди новой,
    и три её числа проект видит ПЕРВЫМ, а не после списка новых правил. Задача
    #47 приходит извне и раз в сутки; это число — в каждом прогоне preflight.

    Отказом оно **пока** не является, и это названо, а не умолчано: таких
    записей больше нуля, и красное на них приучало бы пропускать красное
    (051). Сколько их — печатает каждый прогон preflight, и число здесь не
    повторяется намеренно: вписанное рукой, оно уже устарело однажды — стояло
    «двадцать» при двух (правила 005, 215). Отказ включается, когда счёт
    дойдёт до нуля, — иначе гейт заводится не для того, чтобы держать
    достигнутое, а для того, чтобы кричать о долге, и его выключат раньше, чем
    он пригодится.
    """


def адреса(where: str) -> list[str]:
    """Адреса, названные в `where`. Пустой список — прозы вместо адреса."""
    return _АДРЕС.findall(where)


def _существует(адрес: str, root: Path) -> bool:
    """Разрешается ли адрес в дереве. Образец с `*` — по совпадению."""
    if "*" in адрес:
        return any(root.glob(адрес))
    return (root / адрес).exists()


#: Статусы, которые в раскладке идут своей графой, а не механизмом.
_ГРАФА_СТАТУСА = {
    "not-applicable": "not_applicable",
    "rejected": "rejected",
    "unreviewed": "unreviewed",
}


def _раскладка(правила: dict[str, object]) -> dict[str, int]:
    """Счёт по графам: статус вне `active` — своя графа, `active` — механизм."""
    итог: dict[str, int] = {"total": len(правила)}
    for графа in _ГРАФА_СТАТУСА.values():
        итог[графа] = 0
    for запись in правила.values():
        статус = запись.get("status") if isinstance(запись, dict) else None
        if статус in _ГРАФА_СТАТУСА:
            графа = _ГРАФА_СТАТУСА[статус]
        elif статус == "active" and isinstance(запись, dict):
            графа = str(запись.get("mechanism") or "none")
        else:
            графа = "invalid"
        итог[графа] = итог.get(графа, 0) + 1
    return итог


def check_answer(данные: object, *, root: Path) -> Результат:
    """Сверить ответ с контрактом каталога.

    Записи разбираются **все**, а не до первой негодной: две поломки за один
    прогон дешевле двух прогонов, и «первая красная» скрывает вторую.
    """
    находки: list[Находка] = []
    if not isinstance(данные, dict):
        return Результат(
            [Находка("—", "ответ не объект — разбирать нечего")], записей=0, с_адресом=0
        )

    схема = данные.get("schema")
    if схема != СХЕМА_ОТВЕТА:
        находки.append(
            Находка(
                "—",
                f"schema ответа {схема!r}, а этот гейт читает "
                f"{СХЕМА_ОТВЕТА!r}. Обе стороны сравнения НАШИ — поле нашего "
                "файла и константа этого репозитория; о чужой стороне здесь не "
                "утверждается ничего, её версию сверяет прогон входящих. "
                "Это версия ФОРМАТА ОТВЕТА, а не выгрузки и не выпуска "
                "каталога: одним ключом зовутся три разных числа, и правило "
                "164 родилось на этой путанице",
            )
        )

    правила = данные.get("rules")
    if not isinstance(правила, dict) or not правила:
        находки.append(Находка("—", "в ответе нет ни одной записи о правилах"))
        return Результат(находки, записей=0, с_адресом=0)

    раскладка = _раскладка(правила)
    с_адресом = 0
    ничем = 0
    без_держимости = 0
    for номер, запись in sorted(правила.items()):
        if not isinstance(запись, dict):
            находки.append(Находка(номер, "запись не объект"))
            continue

        статус = запись.get("status")
        if статус not in СТАТУСЫ:
            находки.append(Находка(номер, f"статус {статус!r} не из {sorted(СТАТУСЫ)}"))
            continue

        механизм = запись.get("mechanism")
        if механизм in УСТАРЕВШИЕ_МЕХАНИЗМЫ:
            находки.append(
                Находка(
                    номер,
                    f"механизм {механизм!r} объявлен контрактом устаревшим — "
                    f"выберите из {sorted(МЕХАНИЗМЫ)}",
                )
            )
            continue

        if (
            статус in {"rejected", "not-applicable"}
            and not str(запись.get("why", "")).strip()
        ):
            находки.append(
                Находка(номер, f"статус {статус} без причины в why — это не ответ")
            )
            continue

        поля = поля_1_7(номер, запись, статус=статус, механизм=механизм, root=root)
        находки.extend(поля)

        if статус != "active":
            continue

        if механизм not in МЕХАНИЗМЫ:
            находки.append(
                Находка(номер, f"active без механизма из {sorted(МЕХАНИЗМЫ)}")
            )
            continue

        if механизм == "none":
            # Механизма нет — адреса быть не может, и это законно, если названо.
            # Но «названо» и «держится» — разные вещи, и первое считается тоже:
            # `active` без механизма означает «правило объявлено действующим и
            # не действует» (правило 177).
            ничем += 1
            if "holdable" not in запись:
                без_держимости += 1
            if not str(запись.get("machine_half", "")).strip():
                находки.append(
                    Находка(
                        номер,
                        "active с mechanism=none обязан назвать machine_half — "
                        "ЧТО следует из данных целиком и почему не построено",
                    )
                )
            if not str(запись.get("where", "")).strip():
                находки.append(
                    Находка(
                        номер, "active с mechanism=none обязан назвать, чем держится"
                    )
                )
            continue

        if механизм in НЕ_КРАСНЕЮТ and "holdable" not in запись:
            без_держимости += 1

        if механизм == "skill":
            # Адрес навыка — поле skill, а не where; его форму проверяет
            # поля_1_7. Навык не краснеет, поэтому в счёт «с адресом» гейта он
            # не идёт.
            continue

        where = str(запись.get("where", ""))
        найденные = адреса(where)
        if not найденные:
            находки.append(
                Находка(
                    номер,
                    "where не называет ни одного адреса. Гейт, чей адрес нельзя "
                    "назвать, обычно и не гейт: проза рядом с адресом разрешена, "
                    "вместо адреса — нет",
                )
            )
            continue

        с_адресом += 1
        мёртвые = [а for а in найденные if not _существует(а, root)]
        if мёртвые:
            находки.append(
                Находка(
                    номер,
                    f"адрес в дереве не разрешается: {', '.join(мёртвые)}. "
                    "Переименование переживает такой ответ молча — он остаётся "
                    "правдоподобным",
                )
            )

    return Результат(
        находки,
        записей=len(правила),
        с_адресом=с_адресом,
        без_держимости=без_держимости,
        ничем=ничем,
        раскладка=раскладка,
    )


def поля_1_7(
    номер: str,
    запись: dict[str, object],
    *,
    статус: object,
    механизм: object,
    root: Path,
) -> list[Находка]:
    """Форма и связи полей формата 1.7 — там, где они есть.

    Каждая проверка — из таблицы полей контракта, дословно по смыслу: где поле
    обязательно, где запрещено, что требует соседа.
    """
    находки: list[Находка] = []
    if "document_reason" in запись:
        находки.append(
            Находка(
                номер,
                "document_reason — прежнее имя holdable: каталог читает его на "
                "входе, но у себя оно не пишется",
            )
        )

    держимость = запись.get("holdable")
    if держимость is not None:
        if держимость not in ДЕРЖИМОСТЬ:
            находки.append(
                Находка(номер, f"holdable {держимость!r} не из {sorted(ДЕРЖИМОСТЬ)}")
            )
        if статус != "active" or механизм not in НЕ_КРАСНЕЮТ:
            находки.append(
                Находка(
                    номер,
                    "holdable спрашивается только у active с механизмом, который "
                    f"не краснеет ({', '.join(sorted(НЕ_КРАСНЕЮТ))})",
                )
            )
        if not str(запись.get("why", "")).strip():
            находки.append(Находка(номер, "holdable без причины в why"))
        if держимость == "conditional" and not str(запись.get("awaiting", "")).strip():
            находки.append(
                Находка(номер, "holdable=conditional без события в awaiting")
            )
        if держимость == "refused" and not str(запись.get("machine_half", "")).strip():
            находки.append(
                Находка(
                    номер,
                    "holdable=refused без замера отказа в machine_half (213)",
                )
            )

    if "awaiting" in запись and механизм in {"gate", "pipeline"}:
        находки.append(Находка(номер, f"awaiting запрещён при mechanism={механизм}"))

    навык = запись.get("skill")
    if механизм == "skill" and not навык:
        находки.append(Находка(номер, "mechanism=skill без адреса навыка в skill"))
    if навык is not None:
        if механизм == "none":
            находки.append(Находка(номер, "skill запрещён при mechanism=none"))
        находки.extend(_проверить_навык(номер, навык, root))

    сверено = запись.get("analysed")
    решено = запись.get("decided")
    for имя, значение in (("analysed", сверено), ("decided", решено)):
        if значение is not None and not (
            isinstance(значение, str) and _ДАТА.match(значение)
        ):
            находки.append(Находка(номер, f"{имя} не дата ГГГГ-ММ-ДД: {значение!r}"))
    if решено is not None and сверено is None:
        находки.append(
            Находка(номер, "decided без analysed: решают, посмотрев, а не наоборот")
        )
    if isinstance(решено, str) and isinstance(сверено, str) and решено > сверено:
        находки.append(Находка(номер, f"decided {решено} позже analysed {сверено}"))
    return находки


def _проверить_навык(номер: str, навык: object, root: Path) -> list[Находка]:
    """Адрес навыка: свой каталог с `SKILL.md` либо навык плагина каталога."""
    if not isinstance(навык, str) or not навык.strip():
        return [Находка(номер, f"skill не адрес: {навык!r}")]
    if _НАВЫК_ПЛАГИНА.match(навык):
        # Навык плагина живёт в дереве КАТАЛОГА; сверяет его каталог, а не мы.
        return []
    путь = root / навык / "SKILL.md"
    if not навык.startswith(".claude/skills/") or not путь.is_file():
        return [
            Находка(
                номер,
                f"skill {навык!r}: ни .claude/skills/<имя> с SKILL.md, ни "
                "<плагин>:<имя>",
            )
        ]
    return []


def check_tree(root: Path) -> Результат:
    """Прочитать ответ проекта и сверить его.

    Отсутствие файла — не «чисто»: проект объявил себя потребителем каталога, и
    молчание вместо ответа неотличимо от согласия со всеми правилами сразу.
    """
    путь = root / ОТВЕТ
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return Результат(
            [Находка("—", f"{ОТВЕТ.as_posix()} не найден — ответа каталогу нет")],
            записей=0,
            с_адресом=0,
        )
    except (OSError, ValueError) as отказ:
        return Результат(
            [Находка("—", f"{ОТВЕТ.as_posix()} не прочитан: {отказ}")],
            записей=0,
            с_адресом=0,
        )
    return check_answer(данные, root=root)


def сверить_выгрузку(путь: Path, *, ожидается: str = СХЕМА_ВЫГРУЗКИ) -> str | None:
    """Сверить версию выгрузки каталога с объявленной здесь. `None` — сошлось.

    Единственная сверка в этом файле, у которой одна сторона ЧУЖАЯ. Ради неё
    она и заведена: подъём версии у издателя иначе не заметит ничто, а ответ
    останется правдоподобным (#85, правило 157).

    Отсутствие файла — тоже отказ, а не пропуск: выгрузку кладёт прогон, и её
    отсутствие означает, что он не отработал, а не что версия сошлась.
    """
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as отказ:
        return f"выгрузка каталога не прочитана — {отказ}"

    схема = данные.get("schema") if isinstance(данные, dict) else None
    if схема == ожидается:
        return None
    return (
        f"версия выгрузки каталога {схема!r}, а здесь объявлено {ожидается!r}. "
        "Контракт полагается ПЕРЕЧИТАТЬ и поднять константу заходом, а не "
        "разбирать выгрузку как получится: незнакомое поле молча пропустится, "
        "а изменившийся смысл знакомого — нет"
    )


def main(argv: Sequence[str] | None = None) -> int:
    force_utf8_output()

    import argparse

    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--root", default=".", help="корень дерева")
    parser.add_argument(
        "--catalogue-export",
        default="",
        help="путь к export/rules.json каталога: сверить ЧУЖУЮ версию (#85)",
    )
    аргументы = parser.parse_args(argv)

    if аргументы.catalogue_export:
        расхождение = сверить_выгрузку(Path(аргументы.catalogue_export))
        if расхождение is not None:
            print(f"::error::{расхождение}", file=sys.stderr)
            return EXIT_FAILED
        print(f"версия выгрузки каталога сошлась: {СХЕМА_ВЫГРУЗКИ}")
        return 0

    try:
        результат = check_tree(Path(аргументы.root).resolve())
    except OSError as отказ:
        print(f"ответ не проверен: {отказ}", file=sys.stderr)
        return EXIT_BROKEN

    for находка in результат.находки:
        print(f"::error::{находка}")

    if результат.находки:
        print(
            f"\nнегодных записей ответа: {len(результат.находки)} "
            f"(записей {результат.записей}, с адресом {результат.с_адресом}, "
            f"ничем не держится {результат.ничем})",
            file=sys.stderr,
        )
        return EXIT_FAILED

    print(
        f"ответ каталогу разрешим "
        f"(записей {результат.записей}, с адресом {результат.с_адресом}, "
        f"ничем не держится {результат.ничем})"
    )
    # Отдельной строкой, а не четвёртым числом в первой: три числа первой
    # строки — Ступень 0 свода (CLAUDE.md), их читают и сравнивают. Это — остаток
    # перечитывания по формату 1.7 (#139).
    print(f"без вердикта «можно ли машиной» (holdable): {результат.без_держимости}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
